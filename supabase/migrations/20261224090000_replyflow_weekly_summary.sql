-- A weekly summary for the owner: money in and out, what customers owe, what is owed to suppliers,
-- low stock, orders due, and customers waiting on a reply. Built every Monday for the week just
-- gone, kept so earlier weeks can be looked back on, and announced with a push notification that
-- carries no figures. Only administrators can read the figures.

create table public.weekly_summaries (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  week_from date not null,
  week_to date not null,
  data jsonb not null,
  created_at timestamptz not null default now(),
  unique (organisation_id, week_from)
);
create index weekly_summaries_org_week_idx on public.weekly_summaries (organisation_id, week_from desc);

alter table public.weekly_summaries enable row level security;
create policy "administrators read their weekly summaries" on public.weekly_summaries
  for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
grant select on public.weekly_summaries to authenticated;
grant all on public.weekly_summaries to service_role;

-- The figures for one business and one week. Run by the scheduled job and by an administrator's own
-- "refresh" below; nobody else can call it.
create or replace function public.build_weekly_summary(p_org bigint, p_from date, p_to date)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_today date := current_date;
begin
  return (
    with
    customers as (
      select
        sum(case when i.kind = 'invoice' then i.gross_pence else -i.gross_pence end) - o.paid_pence as owed,
        min(i.due_date) filter (where i.kind = 'invoice') as due
      from public.orders o
      join public.invoices i on i.order_id = o.id
      where o.organisation_id = p_org
      group by o.id, o.paid_pence
    ),
    owed as (select owed, due from customers where owed > 0),
    unpaid as (
      select b.gross_pence, b.due_date
      from public.bills b
      where b.organisation_id = p_org and b.voided_at is null and b.paid_date is null
    )
    select jsonb_build_object(
      'week_from', p_from,
      'week_to', p_to,
      'money_in_pence',
        coalesce((select sum(p.amount_pence) from public.order_payments p
                   where p.organisation_id = p_org and p.kind in ('deposit', 'balance')
                     and p.received_at::date between p_from and p_to), 0)
        + coalesce((select sum(e.amount_pence) from public.money_entries e
                     where e.organisation_id = p_org and e.direction = 'in' and e.status = 'done'
                       and e.voided_at is null and e.entry_date between p_from and p_to
                       and e.category not in ('transfer_in', 'owner_invested', 'loan_received')), 0),
      'money_out_pence',
        coalesce((select sum(b.gross_pence) from public.bills b
                   where b.organisation_id = p_org and b.voided_at is null
                     and b.paid_date between p_from and p_to), 0)
        + coalesce((select sum(e.amount_pence) from public.money_entries e
                     where e.organisation_id = p_org and e.direction = 'out' and e.status = 'done'
                       and e.voided_at is null and e.entry_date between p_from and p_to
                       and e.category <> 'transfer_out'), 0),
      'owed_to_you_pence', coalesce((select sum(owed) from owed), 0),
      'owed_to_you_count', (select count(*) from owed),
      'owed_late_pence', coalesce((select sum(owed) from owed where due < v_today), 0),
      'owed_late_count', (select count(*) from owed where due < v_today),
      'you_owe_pence', coalesce((select sum(gross_pence) from unpaid), 0),
      'bills_late_count', (select count(*) from unpaid where due_date < v_today),
      'bills_due_week_count', (select count(*) from unpaid where due_date between v_today and v_today + 7),
      'bills_due_week_pence', coalesce((select sum(gross_pence) from unpaid
                                          where due_date between v_today and v_today + 7), 0),
      'low_stock_count',
        (select count(*) from public.stock_levels l
           join public.stock_items i on i.id = l.id
          where i.organisation_id = p_org and l.active
            and l.reorder_level is not null and l.on_hand <= l.reorder_level),
      'orders_due_count',
        (select count(*) from public.orders o
          where o.organisation_id = p_org
            and o.status not in ('delivered', 'completed', 'cancelled', 'quoted')
            and o.delivery_window_end::date between v_today and v_today + 7),
      'customers_waiting_count',
        (select count(*) from public.contacts c
          where c.organisation_id = p_org
            and (select m.direction from public.messenger_messages m
                  where m.contact_id = c.id order by m.sent_at desc limit 1) = 'inbound')
    )
  );
end;
$$;
revoke execute on function public.build_weekly_summary(bigint, date, date) from public, anon, authenticated;
grant execute on function public.build_weekly_summary(bigint, date, date) to service_role;

-- An administrator builds this week's summary for their own business on demand, so it is there
-- straight away and not only on Monday.
create or replace function public.refresh_my_weekly_summary()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_org bigint := (select private.current_organisation());
  v_to date := current_date - 1;
  v_from date := current_date - 7;
  v_data jsonb;
begin
  if not (select private.is_admin()) then
    raise exception 'Only an administrator can build the weekly summary.' using errcode = '42501';
  end if;
  v_data := public.build_weekly_summary(v_org, v_from, v_to);
  insert into public.weekly_summaries (organisation_id, week_from, week_to, data)
  values (v_org, v_from, v_to, v_data)
  on conflict (organisation_id, week_from) do update set data = excluded.data, created_at = now();
  return v_data;
end;
$$;
revoke execute on function public.refresh_my_weekly_summary() from public, anon;
grant execute on function public.refresh_my_weekly_summary() to authenticated;

-- Every Monday at 06:30 UTC, ask the weekly_summary function to build and announce them. It checks
-- the same Vault key the autopilot uses.
select cron.unschedule(jobid) from cron.job where jobname = 'weekly-summary';
select cron.schedule(
  'weekly-summary',
  '30 6 * * 1',
  $job$
  select net.http_post(
    url := 'https://mdhmuyhtimjkysvsardi.supabase.co/functions/v1/weekly_summary',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-autopilot-key', (select decrypted_secret from vault.decrypted_secrets where name = 'autopilot_key')
    ),
    body := '{}'::jsonb
  );
  $job$
);
