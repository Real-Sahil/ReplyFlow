-- Messenger enquiries from the business Page (official Messenger Platform webhook).
-- The webhook edge function calls record_messenger_message() with the service role.

begin;

alter table public.contacts add column messenger_psid text;
create unique index contacts_messenger_psid_key on public.contacts (messenger_psid)
    where messenger_psid is not null;

create table public.messenger_messages (
    id bigint generated by default as identity primary key,
    mid text not null unique,
    page_id text not null,
    psid text not null,
    contact_id bigint references public.contacts (id) on delete set null,
    deal_id bigint references public.deals (id) on delete set null,
    body text,
    referral jsonb,
    sent_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);
create index messenger_messages_contact_idx on public.messenger_messages (contact_id, sent_at desc);

alter table public.messenger_messages enable row level security;
create policy "staff read" on public.messenger_messages
    for select to authenticated using ((select public.staff_role()) is not null);
grant select on public.messenger_messages to authenticated;
grant all on public.messenger_messages to service_role;

-- Stores one inbound message, creating the contact and an open enquiry when needed.
-- Returns the new message id, or null when Meta redelivers a message already stored.
create or replace function public.record_messenger_message(
    p_page_id text,
    p_psid text,
    p_mid text,
    p_body text,
    p_sent_at timestamptz,
    p_first_name text,
    p_last_name text,
    p_referral jsonb
) returns bigint
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_message_id bigint;
    v_contact_id bigint;
    v_deal_id bigint;
    v_first text;
    v_last text;
begin
    insert into public.messenger_messages (mid, page_id, psid, body, referral, sent_at)
    values (p_mid, p_page_id, p_psid, p_body, p_referral, coalesce(p_sent_at, now()))
    on conflict (mid) do nothing
    returning id into v_message_id;

    if v_message_id is null then
        return null;
    end if;

    select id into v_contact_id from public.contacts where messenger_psid = p_psid;

    if v_contact_id is null then
        v_first := coalesce(nullif(trim(p_first_name), ''), 'Messenger');
        v_last := coalesce(nullif(trim(p_last_name), ''), 'enquiry ' || right(p_psid, 4));
        insert into public.contacts (first_name, last_name, messenger_psid, first_seen, last_seen)
        values (v_first, v_last, p_psid, now(), now())
        returning id into v_contact_id;
    end if;

    select d.id into v_deal_id
    from public.deals d
    where d.contact_ids @> array[v_contact_id]
      and d.archived_at is null
      and d.stage not in ('won', 'lost')
    order by d.created_at desc
    limit 1;

    if v_deal_id is null then
        select 'Messenger enquiry: ' || c.first_name || ' ' || coalesce(c.last_name, '')
        into v_first from public.contacts c where c.id = v_contact_id;
        insert into public.deals (name, stage, contact_ids, description, created_at, updated_at)
        values (trim(v_first), 'opportunity', array[v_contact_id],
                'Started from a Messenger message to the Page.', now(), now())
        returning id into v_deal_id;
    end if;

    update public.messenger_messages
    set contact_id = v_contact_id, deal_id = v_deal_id
    where id = v_message_id;

    return v_message_id;
end;
$$;

revoke execute on function public.record_messenger_message(text, text, text, text, timestamptz, text, text, jsonb)
    from public, anon, authenticated;
grant execute on function public.record_messenger_message(text, text, text, text, timestamptz, text, text, jsonb)
    to service_role;

commit;
