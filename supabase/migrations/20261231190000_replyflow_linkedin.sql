-- LinkedIn: a staff member connects their own LinkedIn account and can post a ReplyFlow post to their
-- own profile. The access token is kept in Vault (encrypted); the browser never sees it. LinkedIn
-- tokens last about 60 days and cannot be renewed in the background, so the expiry is stored and the
-- app asks the person to reconnect.

create table public.linkedin_members (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id),
    sale_id bigint not null references public.sales (id),
    member_id text not null,                  -- LinkedIn's id for the person (the "sub" from sign-in)
    name text not null default '',
    vault_secret_id uuid,
    expires_at timestamptz not null,
    connected_at timestamptz not null default now(),
    unique (organisation_id, sale_id)
);
create index linkedin_members_organisation_idx on public.linkedin_members (organisation_id);

alter table public.linkedin_members enable row level security;
-- A person sees only their own connection, and never the secret pointer.
create policy "own linkedin connection" on public.linkedin_members
    for select to authenticated
    using (sale_id = (select private.staff_id())
           and organisation_id = (select private.current_organisation()));
revoke all on public.linkedin_members from public, anon, authenticated;
grant select (id, organisation_id, sale_id, member_id, name, expires_at, connected_at)
    on public.linkedin_members to authenticated;
grant all on public.linkedin_members to service_role;

-- Where each ReplyFlow post went on LinkedIn. Written only by the Edge Function.
create table public.linkedin_posts (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id),
    post_id bigint not null references public.page_posts (id),
    sale_id bigint not null references public.sales (id),
    urn text not null,
    posted_at timestamptz not null default now(),
    removed_at timestamptz,
    unique (post_id, sale_id)
);
create index linkedin_posts_organisation_idx on public.linkedin_posts (organisation_id);

alter table public.linkedin_posts enable row level security;
create policy "members read their organisation linkedin posts" on public.linkedin_posts
    for select to authenticated
    using (organisation_id = (select private.current_organisation()));
revoke all on public.linkedin_posts from public, anon, authenticated;
grant select on public.linkedin_posts to authenticated;
grant all on public.linkedin_posts to service_role;

-- Saves or replaces one person's token.
create or replace function public.linkedin_member_store(
    p_sale_id bigint,
    p_organisation_id bigint,
    p_member_id text,
    p_name text,
    p_token text,
    p_expires_at timestamptz
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_existing uuid;
    v_secret uuid;
begin
    select vault_secret_id into v_existing
      from public.linkedin_members
     where organisation_id = p_organisation_id and sale_id = p_sale_id;
    if v_existing is null then
        v_secret := vault.create_secret(
            p_token, 'linkedin_' || p_organisation_id || '_' || p_sale_id, 'LinkedIn access token');
    else
        perform vault.update_secret(
            v_existing, p_token, 'linkedin_' || p_organisation_id || '_' || p_sale_id, 'LinkedIn access token');
        v_secret := v_existing;
    end if;

    insert into public.linkedin_members
        (organisation_id, sale_id, member_id, name, vault_secret_id, expires_at, connected_at)
    values
        (p_organisation_id, p_sale_id, p_member_id, p_name, v_secret, p_expires_at, now())
    on conflict (organisation_id, sale_id) do update
        set member_id = excluded.member_id,
            name = excluded.name,
            vault_secret_id = excluded.vault_secret_id,
            expires_at = excluded.expires_at,
            connected_at = now();
end;
$$;

-- The decrypted token for one person, or null when they have not connected or it has expired.
create or replace function public.linkedin_member_token(p_organisation_id bigint, p_sale_id bigint)
returns text
language sql
stable
security definer
set search_path = ''
as $$
    select s.decrypted_secret
      from public.linkedin_members m
      join vault.decrypted_secrets s on s.id = m.vault_secret_id
     where m.organisation_id = p_organisation_id
       and m.sale_id = p_sale_id
       and m.expires_at > now();
$$;

-- Disconnects: forgets the person and empties the stored token.
create or replace function public.linkedin_member_forget(p_organisation_id bigint, p_sale_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_secret uuid;
begin
    select vault_secret_id into v_secret
      from public.linkedin_members
     where organisation_id = p_organisation_id and sale_id = p_sale_id;
    if not found then
        return false;
    end if;
    if v_secret is not null then
        perform vault.update_secret(v_secret, '', null, null);
    end if;
    delete from public.linkedin_members
     where organisation_id = p_organisation_id and sale_id = p_sale_id;
    return true;
end;
$$;

revoke all on function public.linkedin_member_store(bigint, bigint, text, text, text, timestamptz) from public, anon, authenticated;
revoke all on function public.linkedin_member_token(bigint, bigint) from public, anon, authenticated;
revoke all on function public.linkedin_member_forget(bigint, bigint) from public, anon, authenticated;
grant execute on function public.linkedin_member_store(bigint, bigint, text, text, text, timestamptz) to service_role;
grant execute on function public.linkedin_member_token(bigint, bigint) to service_role;
grant execute on function public.linkedin_member_forget(bigint, bigint) to service_role;
