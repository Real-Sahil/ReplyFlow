-- LinkedIn company Pages (the Community Management API, a separate LinkedIn app). An administrator
-- connects LinkedIn and the Pages they administer are saved for the business, with a token each kept in
-- Vault. A Page belongs to one business only. Tokens last about 60 days; the app asks for a reconnect.

create table public.linkedin_pages (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id),
    org_id text not null,                       -- LinkedIn's number for the company Page
    name text not null default '',
    connected_by bigint references public.sales (id),
    vault_secret_id uuid,
    expires_at timestamptz not null,
    connected_at timestamptz not null default now(),
    unique (org_id)
);
create index linkedin_pages_organisation_idx on public.linkedin_pages (organisation_id);

alter table public.linkedin_pages enable row level security;
create policy "members read their organisation linkedin pages" on public.linkedin_pages
    for select to authenticated
    using (organisation_id = (select private.current_organisation()));
revoke all on public.linkedin_pages from public, anon, authenticated;
grant select (id, organisation_id, org_id, name, expires_at, connected_at)
    on public.linkedin_pages to authenticated;
grant all on public.linkedin_pages to service_role;

-- Where each ReplyFlow post went on a company Page. Written only by the Edge Function.
create table public.linkedin_page_posts (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id),
    post_id bigint not null references public.page_posts (id),
    org_id text not null,
    posted_by bigint references public.sales (id),
    urn text not null,
    posted_at timestamptz not null default now(),
    removed_at timestamptz,
    unique (post_id, org_id)
);
create index linkedin_page_posts_organisation_idx on public.linkedin_page_posts (organisation_id);

alter table public.linkedin_page_posts enable row level security;
create policy "members read their organisation linkedin page posts" on public.linkedin_page_posts
    for select to authenticated
    using (organisation_id = (select private.current_organisation()));
revoke all on public.linkedin_page_posts from public, anon, authenticated;
grant select on public.linkedin_page_posts to authenticated;
grant all on public.linkedin_page_posts to service_role;

-- Saves or replaces one Page's token. A Page connected to another business cannot be taken over.
create or replace function public.linkedin_page_store(
    p_organisation_id bigint,
    p_org_id text,
    p_name text,
    p_token text,
    p_expires_at timestamptz,
    p_sale_id bigint
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_owner bigint;
    v_existing uuid;
    v_secret uuid;
begin
    select organisation_id, vault_secret_id into v_owner, v_existing
      from public.linkedin_pages where org_id = p_org_id;
    if found and v_owner <> p_organisation_id then
        raise exception 'This LinkedIn Page is already connected to another business'
            using errcode = '42501';
    end if;

    if v_existing is null then
        v_secret := vault.create_secret(p_token, 'linkedin_page_' || p_org_id, 'LinkedIn Page access token');
    else
        perform vault.update_secret(v_existing, p_token, 'linkedin_page_' || p_org_id, 'LinkedIn Page access token');
        v_secret := v_existing;
    end if;

    insert into public.linkedin_pages
        (organisation_id, org_id, name, connected_by, vault_secret_id, expires_at, connected_at)
    values
        (p_organisation_id, p_org_id, p_name, p_sale_id, v_secret, p_expires_at, now())
    on conflict (org_id) do update
        set name = excluded.name,
            connected_by = excluded.connected_by,
            vault_secret_id = excluded.vault_secret_id,
            expires_at = excluded.expires_at,
            connected_at = now();
end;
$$;

-- The decrypted token for one of a business's Pages, or null when it is not theirs or has expired.
create or replace function public.linkedin_page_token(p_organisation_id bigint, p_org_id text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
    select s.decrypted_secret
      from public.linkedin_pages p
      join vault.decrypted_secrets s on s.id = p.vault_secret_id
     where p.organisation_id = p_organisation_id
       and p.org_id = p_org_id
       and p.expires_at > now();
$$;

-- Disconnects a Page: empties the stored token and forgets the Page.
create or replace function public.linkedin_page_forget(p_organisation_id bigint, p_org_id text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_secret uuid;
begin
    select vault_secret_id into v_secret
      from public.linkedin_pages
     where organisation_id = p_organisation_id and org_id = p_org_id;
    if not found then
        return false;
    end if;
    if v_secret is not null then
        perform vault.update_secret(v_secret, '', null, null);
    end if;
    delete from public.linkedin_pages
     where organisation_id = p_organisation_id and org_id = p_org_id;
    return true;
end;
$$;

revoke all on function public.linkedin_page_store(bigint, text, text, text, timestamptz, bigint) from public, anon, authenticated;
revoke all on function public.linkedin_page_token(bigint, text) from public, anon, authenticated;
revoke all on function public.linkedin_page_forget(bigint, text) from public, anon, authenticated;
grant execute on function public.linkedin_page_store(bigint, text, text, text, timestamptz, bigint) to service_role;
grant execute on function public.linkedin_page_token(bigint, text) to service_role;
grant execute on function public.linkedin_page_forget(bigint, text) to service_role;
