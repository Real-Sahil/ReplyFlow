-- ReplyFlow phase 2: order tracking and the follow-up engine.
--
-- Orders: a lightweight workflow for made-to-order goods (sofas for the first
-- pilot) with quoted and agreed price, deposit and balance in pence, a delivery
-- window, status history and after-sales issues. The sofa configuration lives in
-- a jsonb column so other businesses can store their own options.
--
-- Follow-up engine: generate_followup_tasks() creates tasks for unanswered
-- enquiries, quotes awaiting a reply and orders missing a customer update. It is
-- safe to run repeatedly (a dedupe key stops repeats) and the tasks cancel
-- themselves when the customer progresses.

begin;

-- 1. Settings -----------------------------------------------------------------

create table public.followup_settings (
    id integer primary key default 1,
    enabled boolean not null default true,
    enquiry_stage text not null default 'opportunity',
    enquiry_unanswered_hours integer not null default 24,
    quote_stage text not null default 'proposal-sent',
    quote_chase_days integer not null default 3,
    order_update_days integer not null default 7,
    constraint followup_settings_singleton check (id = 1),
    constraint followup_settings_positive check (
        enquiry_unanswered_hours > 0 and quote_chase_days > 0 and order_update_days > 0
    )
);
insert into public.followup_settings (id) values (1);

-- 2. Orders -------------------------------------------------------------------

create table public.orders (
    id bigint generated by default as identity primary key,
    reference text generated always as ('ORD-' || lpad(id::text, 5, '0')) stored,
    contact_id bigint not null references public.contacts (id) on update cascade on delete restrict,
    deal_id bigint references public.deals (id) on update cascade on delete set null,
    sales_id bigint references public.sales (id),
    status text not null default 'quoted',
    product_summary text,
    configuration jsonb not null default '{}'::jsonb,
    quoted_price_pence bigint,
    agreed_price_pence bigint,
    deposit_required_pence bigint not null default 0,
    paid_pence bigint not null default 0,
    balance_pence bigint generated always as (coalesce(agreed_price_pence, 0) - paid_pence) stored,
    delivery_address text,
    delivery_window_start date,
    delivery_window_end date,
    next_update_due date,
    last_customer_update_at timestamp with time zone,
    notes text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint orders_reference_unique unique (reference),
    constraint orders_status_check check (status in (
        'quoted', 'confirmed', 'deposit_paid', 'in_production', 'ready_for_delivery',
        'delivery_booked', 'delivered', 'completed', 'cancelled'
    )),
    constraint orders_money_check check (
        coalesce(quoted_price_pence, 0) >= 0 and coalesce(agreed_price_pence, 0) >= 0
        and deposit_required_pence >= 0 and paid_pence >= 0
    ),
    constraint orders_configuration_is_object check (jsonb_typeof(configuration) = 'object'),
    constraint orders_delivery_window_order check (
        delivery_window_start is null or delivery_window_end is null
        or delivery_window_end >= delivery_window_start
    )
);

create index orders_contact_id_idx on public.orders (contact_id);
create index orders_deal_id_idx on public.orders (deal_id);
create index orders_status_idx on public.orders (status);
create index orders_next_update_due_idx on public.orders (next_update_due)
    where status not in ('completed', 'cancelled');

create table public.order_status_history (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders (id) on update cascade on delete cascade,
    from_status text,
    to_status text not null,
    changed_by bigint references public.sales (id),
    changed_at timestamp with time zone not null default now()
);
create index order_status_history_order_id_idx on public.order_status_history (order_id);

create table public.after_sales_issues (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders (id) on update cascade on delete cascade,
    summary text not null,
    details text,
    status text not null default 'open',
    sales_id bigint references public.sales (id),
    opened_at timestamp with time zone not null default now(),
    resolved_at timestamp with time zone,
    constraint after_sales_issues_status_check check (status in ('open', 'in_progress', 'resolved'))
);
create index after_sales_issues_order_id_idx on public.after_sales_issues (order_id);

-- 3. Tasks: link to deals and orders, mark automatic ones ------------------------

alter table public.tasks add column deal_id bigint references public.deals (id) on update cascade on delete cascade;
alter table public.tasks add column order_id bigint references public.orders (id) on update cascade on delete cascade;
alter table public.tasks add column source text not null default 'manual';
alter table public.tasks add column dedupe_key text;
alter table public.tasks add column closed_reason text;
alter table public.tasks add constraint tasks_source_check check (source in ('manual', 'auto'));
create unique index tasks_dedupe_key_idx on public.tasks (dedupe_key);
create index tasks_deal_id_idx on public.tasks (deal_id) where done_date is null;
create index tasks_order_id_idx on public.tasks (order_id) where done_date is null;

-- 4. Triggers -------------------------------------------------------------------

create or replace function public.set_updated_at() returns trigger
    language plpgsql
    set search_path = ''
    as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

create trigger "10_orders_set_updated_at"
    before update on public.orders
    for each row execute function public.set_updated_at();

create trigger "20_orders_set_sales_id"
    before insert on public.orders
    for each row execute function public.set_sales_id_default();

create or replace function public.log_order_status() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    if tg_op = 'INSERT' then
        insert into public.order_status_history (order_id, from_status, to_status, changed_by)
        values (new.id, null, new.status, private.staff_id());
    elsif new.status is distinct from old.status then
        insert into public.order_status_history (order_id, from_status, to_status, changed_by)
        values (new.id, old.status, new.status, private.staff_id());
    end if;
    return new;
end;
$$;

create trigger "30_orders_log_status"
    after insert or update of status on public.orders
    for each row execute function public.log_order_status();

-- Automatic reminders cancel themselves when the customer progresses.
create or replace function public.close_auto_tasks(p_deal_id bigint, p_order_id bigint, p_reason text)
    returns void
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    update public.tasks
    set done_date = now(), closed_reason = p_reason
    where source = 'auto' and done_date is null
      and ((p_deal_id is not null and deal_id = p_deal_id)
        or (p_order_id is not null and order_id = p_order_id));
end;
$$;

create or replace function public.on_deal_progressed() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    if new.stage is distinct from old.stage or (new.archived_at is not null and old.archived_at is null) then
        perform public.close_auto_tasks(new.id, null, 'deal moved to ' || new.stage);
    end if;
    return new;
end;
$$;

create trigger "40_deals_close_auto_tasks"
    after update of stage, archived_at on public.deals
    for each row execute function public.on_deal_progressed();

create or replace function public.on_deal_note_added() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    perform public.close_auto_tasks(new.deal_id, null, 'activity recorded');
    return new;
end;
$$;

create trigger "40_deal_notes_close_auto_tasks"
    after insert on public.deal_notes
    for each row execute function public.on_deal_note_added();

create or replace function public.on_order_progressed() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    if new.status is distinct from old.status
       or new.next_update_due is distinct from old.next_update_due
       or new.last_customer_update_at is distinct from old.last_customer_update_at then
        perform public.close_auto_tasks(null, new.id, 'order updated');
    end if;
    return new;
end;
$$;

create trigger "40_orders_close_auto_tasks"
    after update on public.orders
    for each row execute function public.on_order_progressed();

-- 5. The follow-up engine -------------------------------------------------------

create or replace function public.generate_followup_tasks() returns integer
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    s public.followup_settings;
    total integer := 0;
    n integer;
begin
    select * into s from public.followup_settings where id = 1;
    if not found or not s.enabled then
        return 0;
    end if;

    -- New enquiries nobody has answered: no note on the deal and no open task.
    insert into public.tasks (contact_id, deal_id, type, text, due_date, sales_id, source, dedupe_key)
    select c.contact_id, d.id, 'follow-up', 'Reply to new enquiry: ' || d.name, now(), d.sales_id, 'auto',
           'enquiry:' || d.id
    from public.deals d
    cross join lateral (
        select co.id as contact_id from public.contacts co
        where co.id = any (d.contact_ids) order by co.id limit 1
    ) c
    where d.stage = s.enquiry_stage
      and d.archived_at is null
      and d.created_at < now() - make_interval(hours => s.enquiry_unanswered_hours)
      and not exists (select 1 from public.deal_notes n where n.deal_id = d.id)
      and not exists (select 1 from public.tasks t where t.deal_id = d.id and t.done_date is null)
    on conflict (dedupe_key) do nothing;
    get diagnostics n = row_count;
    total := total + n;

    -- Quotes awaiting a reply: the quote has been quiet for too long. The key
    -- carries the last activity date, so a new chase only appears after new activity.
    insert into public.tasks (contact_id, deal_id, type, text, due_date, sales_id, source, dedupe_key)
    select c.contact_id, d.id, 'follow-up', 'Chase quote: ' || d.name, now(), d.sales_id, 'auto',
           'quote:' || d.id || ':' || a.last_activity::date
    from public.deals d
    cross join lateral (
        select co.id as contact_id from public.contacts co
        where co.id = any (d.contact_ids) order by co.id limit 1
    ) c
    cross join lateral (
        select greatest(d.updated_at, coalesce(
            (select max(n.date) from public.deal_notes n where n.deal_id = d.id), d.updated_at)
        ) as last_activity
    ) a
    where d.stage = s.quote_stage
      and d.archived_at is null
      and a.last_activity < now() - make_interval(days => s.quote_chase_days)
      and not exists (select 1 from public.tasks t where t.deal_id = d.id and t.done_date is null)
    on conflict (dedupe_key) do nothing;
    get diagnostics n = row_count;
    total := total + n;

    -- Orders whose next customer update is due (or that have gone quiet).
    insert into public.tasks (contact_id, order_id, type, text, due_date, sales_id, source, dedupe_key)
    select o.contact_id, o.id, 'follow-up', 'Update customer on order ' || o.reference, now(), o.sales_id, 'auto',
           'order:' || o.id || ':' || due.d
    from public.orders o
    cross join lateral (
        select coalesce(
            o.next_update_due,
            (coalesce(o.last_customer_update_at, o.created_at) + make_interval(days => s.order_update_days))::date
        ) as d
    ) due
    where o.status not in ('completed', 'cancelled')
      and due.d <= current_date
      and not exists (select 1 from public.tasks t where t.order_id = o.id and t.done_date is null)
    on conflict (dedupe_key) do nothing;
    get diagnostics n = row_count;
    total := total + n;

    return total;
end;
$$;

-- 6. Row level security and grants ------------------------------------------------

alter table public.followup_settings enable row level security;
alter table public.orders enable row level security;
alter table public.order_status_history enable row level security;
alter table public.after_sales_issues enable row level security;

create policy "staff read" on public.followup_settings
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "admins update" on public.followup_settings
    for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

create policy "staff read" on public.orders
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "agents insert" on public.orders
    for insert to authenticated with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "agents update" on public.orders
    for update to authenticated
    using ((select public.staff_role()) in ('admin', 'agent'))
    with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "admins delete" on public.orders
    for delete to authenticated using ((select public.is_admin()));

create policy "staff read" on public.order_status_history
    for select to authenticated using ((select public.staff_role()) is not null);

create policy "staff read" on public.after_sales_issues
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "agents insert" on public.after_sales_issues
    for insert to authenticated with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "agents update" on public.after_sales_issues
    for update to authenticated
    using ((select public.staff_role()) in ('admin', 'agent'))
    with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "admins delete" on public.after_sales_issues
    for delete to authenticated using ((select public.is_admin()));

grant select, update on public.followup_settings to authenticated;
grant select, insert, update, delete on public.orders, public.after_sales_issues to authenticated;
grant select on public.order_status_history to authenticated;
grant all on public.followup_settings, public.orders, public.order_status_history, public.after_sales_issues to service_role;

-- Only the scheduler and the server side may run the engine and the helpers.
revoke execute on function
    public.generate_followup_tasks(),
    public.close_auto_tasks(bigint, bigint, text),
    public.log_order_status(),
    public.on_deal_progressed(),
    public.on_deal_note_added(),
    public.on_order_progressed(),
    public.set_updated_at()
    from public, anon, authenticated;
grant execute on function public.generate_followup_tasks(), public.close_auto_tasks(bigint, bigint, text) to service_role;

commit;
