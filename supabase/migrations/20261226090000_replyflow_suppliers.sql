-- Suppliers, and the link from a stock item to who it is bought from, so low stock turns into a
-- shopping list grouped by supplier. A supplier is archived, never deleted.

create table public.suppliers (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  name text not null check (char_length(trim(name)) > 0),
  contact_name text,
  phone text,
  email text,
  terms text,
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint suppliers_name_unique unique (organisation_id, name)
);
create index suppliers_created_by_idx on public.suppliers (created_by);

create or replace function private.suppliers_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null then
      raise exception 'Only staff can add suppliers.' using errcode = '42501';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.updated_at := now();
  end if;
  return new;
end;
$$;
revoke execute on function private.suppliers_before_write() from public, anon, authenticated;

create trigger "10_suppliers_before_write" before insert or update on public.suppliers
  for each row execute function private.suppliers_before_write();
create trigger "90_suppliers_audit" after insert or update or delete on public.suppliers
  for each row execute function private.audit_row();

alter table public.suppliers enable row level security;
create policy "staff read suppliers" on public.suppliers for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) is not null);
create policy "staff add suppliers" on public.suppliers for insert to authenticated
  with check (
    (select public.staff_role()) in ('admin', 'agent')
    and organisation_id = (select private.current_organisation())
  );
create policy "staff change suppliers" on public.suppliers for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) in ('admin', 'agent'))
  with check (organisation_id = (select private.current_organisation()));

grant select on public.suppliers to authenticated;
grant insert (name, contact_name, phone, email, terms, notes, active) on public.suppliers to authenticated;
grant update (name, contact_name, phone, email, terms, notes, active) on public.suppliers to authenticated;
grant all on public.suppliers to service_role;

-- Who a stock item is bought from, and how much to buy when it runs low.
alter table public.stock_items
  add column supplier_id bigint references public.suppliers (id) on delete set null,
  add column reorder_quantity numeric(12, 3) check (reorder_quantity is null or reorder_quantity > 0);
create index stock_items_supplier_idx on public.stock_items (supplier_id);
grant insert (supplier_id, reorder_quantity) on public.stock_items to authenticated;
grant update (supplier_id, reorder_quantity) on public.stock_items to authenticated;

-- A stock item can only point at a supplier of its own business.
create or replace function private.stock_items_supplier_check() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if new.supplier_id is not null and not exists (
    select 1 from public.suppliers s
    where s.id = new.supplier_id and s.organisation_id = new.organisation_id
  ) then
    raise exception 'That supplier belongs to another business.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.stock_items_supplier_check() from public, anon, authenticated;
create trigger "20_stock_items_supplier_check" before insert or update on public.stock_items
  for each row execute function private.stock_items_supplier_check();
