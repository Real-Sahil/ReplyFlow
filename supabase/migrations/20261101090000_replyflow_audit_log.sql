-- Who changed what: an append-only history of edits to the records that matter.

create table public.audit_log (
    id bigint generated by default as identity primary key,
    table_name text not null,
    record_id bigint not null,
    action text not null check (action in ('insert', 'update', 'delete')),
    actor_id bigint references public.sales (id) on delete set null,
    changed_at timestamptz not null default now(),
    -- update: {"column": {"old": ..., "new": ...}}; insert and delete: the row itself
    changes jsonb not null
);
create index audit_log_record_idx on public.audit_log (table_name, record_id, changed_at desc);

alter table public.audit_log enable row level security;
create policy "staff read" on public.audit_log
    for select to authenticated using ((select public.staff_role()) is not null);
grant select on public.audit_log to authenticated;
grant all on public.audit_log to service_role;

-- Columns that change as a side effect of normal use and would only add noise.
create or replace function private.audit_row() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_noise text[] := array['updated_at', 'created_at', 'fts', 'last_seen', 'messenger_read_at', 'index'];
    v_old jsonb;
    v_new jsonb;
    v_diff jsonb := '{}'::jsonb;
    v_key text;
    v_id bigint;
begin
    if tg_op = 'INSERT' then
        v_new := to_jsonb(new) - v_noise;
        insert into public.audit_log (table_name, record_id, action, actor_id, changes)
        values (tg_table_name, (to_jsonb(new) ->> 'id')::bigint, 'insert', private.staff_id(), v_new);
        return new;
    elsif tg_op = 'DELETE' then
        v_old := to_jsonb(old) - v_noise;
        insert into public.audit_log (table_name, record_id, action, actor_id, changes)
        values (tg_table_name, (to_jsonb(old) ->> 'id')::bigint, 'delete', private.staff_id(), v_old);
        return old;
    end if;

    v_old := to_jsonb(old) - v_noise;
    v_new := to_jsonb(new) - v_noise;
    for v_key in select jsonb_object_keys(v_new) loop
        if v_old -> v_key is distinct from v_new -> v_key then
            v_diff := v_diff || jsonb_build_object(v_key, jsonb_build_object('old', v_old -> v_key, 'new', v_new -> v_key));
        end if;
    end loop;
    if v_diff <> '{}'::jsonb then
        v_id := (to_jsonb(new) ->> 'id')::bigint;
        insert into public.audit_log (table_name, record_id, action, actor_id, changes)
        values (tg_table_name, v_id, 'update', private.staff_id(), v_diff);
    end if;
    return new;
end;
$$;

revoke execute on function private.audit_row() from public, anon, authenticated;

create trigger "90_orders_audit" after insert or update or delete on public.orders
    for each row execute function private.audit_row();
create trigger "90_deals_audit" after insert or update or delete on public.deals
    for each row execute function private.audit_row();
create trigger "90_contacts_audit" after insert or update or delete on public.contacts
    for each row execute function private.audit_row();
create trigger "90_products_audit" after insert or update or delete on public.products
    for each row execute function private.audit_row();
