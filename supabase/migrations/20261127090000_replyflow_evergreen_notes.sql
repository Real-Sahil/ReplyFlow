-- Evergreen posts: a published post marked evergreen is offered again every 60 days as a
-- draft for review. Nothing is published without a person approving it.
alter table public.page_posts
    add column evergreen boolean not null default false,
    add column recycled_from bigint references public.page_posts (id) on delete set null;

create or replace function public.recycle_evergreen_posts() returns integer
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    total integer;
begin
    insert into public.page_posts (
        message, product_id, image_url, link_url, status, source, ai_model,
        media_path, media_name, media_type, recycled_from, created_by
    )
    select p.message, p.product_id, p.image_url, p.link_url, 'draft', p.source, p.ai_model,
           p.media_path, p.media_name, p.media_type, p.id, p.created_by
    from public.page_posts p
    where p.evergreen
      and p.status = 'published'
      and p.published_at < now() - interval '60 days'
      and not exists (
          select 1 from public.page_posts r
          where r.recycled_from = p.id and r.created_at > now() - interval '60 days'
      );
    get diagnostics total = row_count;
    return total;
end;
$$;

revoke execute on function public.recycle_evergreen_posts() from public, anon, authenticated;
grant execute on function public.recycle_evergreen_posts() to service_role;

select cron.schedule('replyflow-evergreen', '0 7 * * *', $job$ select public.recycle_evergreen_posts(); $job$);

-- Internal notes on a customer's Messenger conversation. They are never sent to the customer.
create table public.messenger_internal_notes (
    id bigint generated by default as identity primary key,
    contact_id bigint not null references public.contacts (id) on delete cascade,
    body text not null check (char_length(body) between 1 and 2000),
    sales_id bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now()
);
create index messenger_internal_notes_contact_idx on public.messenger_internal_notes (contact_id, created_at);

alter table public.messenger_internal_notes enable row level security;
create policy "staff read" on public.messenger_internal_notes
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "staff write" on public.messenger_internal_notes
    for insert to authenticated with check ((select public.staff_role()) is not null);
grant select, insert on public.messenger_internal_notes to authenticated;
grant all on public.messenger_internal_notes to service_role;
