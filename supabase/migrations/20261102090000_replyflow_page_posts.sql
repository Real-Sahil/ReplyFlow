-- Posts composed in ReplyFlow and published to the Facebook Page (official Pages API).

create table public.page_posts (
    id bigint generated by default as identity primary key,
    message text not null check (length(trim(message)) > 0 and length(message) <= 8000),
    product_id bigint references public.products (id) on delete set null,
    image_url text,
    link_url text,
    status text not null default 'draft' check (status in ('draft', 'scheduled', 'published', 'failed')),
    scheduled_for timestamptz,
    published_at timestamptz,
    fb_post_id text,
    error text,
    created_by bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint page_posts_schedule_check check (status <> 'scheduled' or scheduled_for is not null)
);
create index page_posts_status_idx on public.page_posts (status, scheduled_for);

create trigger "10_page_posts_set_updated_at"
    before update on public.page_posts
    for each row execute function public.set_updated_at();

create or replace function public.page_posts_set_creator() returns trigger
    language plpgsql
    set search_path = ''
    as $$
begin
    new.created_by := coalesce(new.created_by, private.staff_id());
    return new;
end;
$$;
revoke execute on function public.page_posts_set_creator() from public, anon, authenticated;

create trigger "20_page_posts_set_creator"
    before insert on public.page_posts
    for each row execute function public.page_posts_set_creator();

alter table public.page_posts enable row level security;
create policy "staff read" on public.page_posts
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "agents insert" on public.page_posts
    for insert to authenticated with check ((select public.staff_role()) in ('admin', 'agent'));
-- Posts that already went to Facebook are changed only by the publish function.
create policy "agents update drafts" on public.page_posts
    for update to authenticated
    using ((select public.staff_role()) in ('admin', 'agent') and status in ('draft', 'failed'))
    with check ((select public.staff_role()) in ('admin', 'agent') and status in ('draft', 'failed'));
create policy "admins delete drafts" on public.page_posts
    for delete to authenticated using ((select public.is_admin()) and status in ('draft', 'failed'));

grant select, insert, update, delete on public.page_posts to authenticated;
grant all on public.page_posts to service_role;

create trigger "90_page_posts_audit" after insert or update or delete on public.page_posts
    for each row execute function private.audit_row();
