-- Invoices and credit notes, per business, as evidence for the accountant.
--
-- Rules that make them usable as evidence:
--   * Created only through issue_invoice(), never inserted by the browser, and never edited or
--     deleted afterwards. A mistake is corrected with a credit note.
--   * Numbers are sequential and never skip: they come from a counter that rolls back with the
--     document if anything fails. Invoices and credit notes have their own sequences.
--   * Every document points at its order, and keeps a copy of the order's reference, summary
--     and note as they were when it was issued, so an export row says what it belongs to.
--   * The seller's name, address and VAT number, the VAT switch and the price basis are copied
--     onto the document, so later changes to the settings never rewrite an old invoice.
--   * VAT is worked out once for each rate on the total of its lines, rounded half up, then
--     shared back across the lines. A business without VAT registration gets no VAT at all.

alter table public.business_settings
  add column credit_prefix text not null default 'CN-' check (char_length(credit_prefix) <= 10),
  add column next_credit_number integer not null default 1 check (next_credit_number >= 1);

grant insert (credit_prefix) on public.business_settings to authenticated;
grant update (credit_prefix) on public.business_settings to authenticated;

create table public.invoices (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  kind text not null check (kind in ('invoice', 'credit_note')),
  number text not null,
  order_id bigint not null references public.orders (id) on delete restrict,
  order_reference text not null,
  order_summary text,
  order_note text,
  credit_for_id bigint references public.invoices (id) on delete restrict,
  contact_id bigint references public.contacts (id) on delete set null,
  customer_name text,
  customer_address text,
  issue_date date not null,
  tax_point date not null,
  due_date date,
  supplier_name text not null,
  supplier_address text,
  supplier_vat_number text,
  vat_registered boolean not null,
  prices_include_vat boolean not null,
  net_pence bigint not null check (net_pence >= 0),
  vat_pence bigint not null check (vat_pence >= 0),
  gross_pence bigint not null check (gross_pence > 0),
  note text,
  created_by bigint references public.sales (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint invoices_number_unique unique (organisation_id, number),
  constraint invoices_credit_links_invoice check (
    (kind = 'credit_note') = (credit_for_id is not null)
  )
);
create index invoices_org_date_idx on public.invoices (organisation_id, issue_date desc);
create index invoices_order_idx on public.invoices (order_id);
create index invoices_credit_for_idx on public.invoices (credit_for_id);

create table public.invoice_lines (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.invoices (id) on delete restrict,
  organisation_id bigint not null references public.organisations (id),
  position smallint not null,
  description text not null,
  quantity numeric(10, 2) not null check (quantity > 0),
  unit_amount_pence bigint not null check (unit_amount_pence >= 0),
  vat_code text not null references public.vat_rates (code),
  vat_percent numeric(5, 2) not null,
  net_pence bigint not null,
  vat_pence bigint not null,
  gross_pence bigint not null,
  constraint invoice_lines_position_unique unique (invoice_id, position)
);
create index invoice_lines_org_idx on public.invoice_lines (organisation_id);

alter table public.invoices enable row level security;
alter table public.invoice_lines enable row level security;

create policy "staff read their invoices" on public.invoices
  for select to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) is not null
  );
create policy "staff read their invoice lines" on public.invoice_lines
  for select to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) is not null
  );

revoke all on public.invoices, public.invoice_lines from anon, authenticated;
grant select on public.invoices, public.invoice_lines to authenticated;
grant all on public.invoices, public.invoice_lines to service_role;

-- One row per line, with credit notes as negative amounts, for the export and the list.
create view public.invoice_ledger
  with (security_invoker = on)
  as
select
  l.id as line_id,
  i.id as invoice_id,
  i.number,
  i.kind,
  i.issue_date,
  i.tax_point,
  i.due_date,
  i.order_id,
  i.order_reference,
  i.order_summary,
  i.order_note,
  i.note as document_note,
  i.customer_name,
  cf.number as credit_for_number,
  i.supplier_vat_number,
  i.vat_registered,
  l.position,
  l.description,
  l.quantity,
  l.vat_code,
  l.vat_percent,
  case when i.kind = 'credit_note' then -l.net_pence else l.net_pence end as net_pence,
  case when i.kind = 'credit_note' then -l.vat_pence else l.vat_pence end as vat_pence,
  case when i.kind = 'credit_note' then -l.gross_pence else l.gross_pence end as gross_pence
from public.invoice_lines l
join public.invoices i on i.id = l.invoice_id
left join public.invoices cf on cf.id = i.credit_for_id;

grant select on public.invoice_ledger to authenticated;
grant select on public.invoice_ledger to service_role;

-- Issues an invoice, or a credit note against an earlier invoice, for one order.
-- p_lines: [{ "description": "...", "quantity": 1, "unit_amount_pence": 12000, "vat_code": "S" }]
-- Amounts are in pence and are VAT-inclusive or not according to the business's setting.
create or replace function public.issue_invoice(
  p_order_id bigint,
  p_kind text,
  p_credit_for bigint,
  p_lines jsonb,
  p_issue_date date default current_date,
  p_due_date date default null,
  p_note text default null
) returns bigint
  language plpgsql security definer
  set search_path = ''
  as $$
declare
  v_org bigint := (select private.current_organisation());
  v_staff bigint := (select private.staff_id());
  s public.business_settings%rowtype;
  o public.orders%rowtype;
  v_customer text;
  v_original public.invoices%rowtype;
  v_credited bigint;
  v_prefix text;
  v_seq integer;
  v_number text;
  v_net bigint;
  v_vat bigint;
  v_id bigint;
  v_count integer;
  v_matched integer;
begin
  if v_org is null or v_staff is null then
    raise exception 'Only staff can issue invoices.' using errcode = '42501';
  end if;
  if p_kind not in ('invoice', 'credit_note') then
    raise exception 'Unknown document type.';
  end if;
  if jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) not between 1 and 50 then
    raise exception 'Add between 1 and 50 lines.';
  end if;

  select * into s from public.business_settings where organisation_id = v_org for update;
  if not found or coalesce(nullif(trim(s.legal_name), ''), nullif(trim(s.trading_name), '')) is null then
    raise exception 'Add the business name under Business and VAT first.';
  end if;

  select * into o from public.orders where id = p_order_id and organisation_id = v_org;
  if not found then
    raise exception 'That order was not found.';
  end if;

  if p_kind = 'credit_note' then
    select * into v_original from public.invoices
      where id = p_credit_for and organisation_id = v_org and kind = 'invoice' and order_id = o.id;
    if not found then
      raise exception 'A credit note must credit an invoice on the same order.';
    end if;
  elsif p_credit_for is not null then
    raise exception 'Only a credit note can credit another document.';
  end if;

  -- Plain DML can use the variables above; CREATE TABLE AS cannot, so the tables are made first.
  create temp table _inv_lines (
    pos smallint, description text, quantity numeric, unit_amount_pence bigint,
    vat_code text, vat_percent numeric, amount bigint
  ) on commit drop;
  create temp table _inv_bands (
    vat_code text, vat_percent numeric, amount bigint, net bigint, vat bigint
  ) on commit drop;

  insert into _inv_lines
  with l as (
    select (t.ord)::smallint as pos,
           trim(t.e ->> 'description') as description,
           (t.e ->> 'quantity')::numeric as quantity,
           (t.e ->> 'unit_amount_pence')::bigint as unit_amount_pence,
           t.e ->> 'vat_code' as code
    from jsonb_array_elements(p_lines) with ordinality as t(e, ord)
  )
  select l.pos, l.description, l.quantity, l.unit_amount_pence,
         case when s.vat_registered then l.code else 'O' end as vat_code,
         r.rate_percent as vat_percent,
         floor(l.quantity * l.unit_amount_pence + 0.5)::bigint as amount
  from l
  join public.vat_rates r on r.code = case when s.vat_registered then l.code else 'O' end;

  select count(*) into v_count from jsonb_array_elements(p_lines);
  select count(*) into v_matched from _inv_lines;
  if v_matched <> v_count then
    raise exception 'A line has an unknown VAT code.';
  end if;
  if exists (select 1 from _inv_lines where description is null or description = ''
             or quantity <= 0 or unit_amount_pence < 0) then
    raise exception 'Every line needs a description, a quantity above zero and a price.';
  end if;

  -- Per rate: the net and VAT of the total, then shared back across the lines in order.
  insert into _inv_bands
  with b as (
    select vat_code, vat_percent, sum(amount) as amount from _inv_lines group by 1, 2
  )
  select vat_code, vat_percent, amount,
         case when vat_percent = 0 then amount
              when s.prices_include_vat then floor(amount * 100.0 / (100 + vat_percent) + 0.5)::bigint
              else amount end as net,
         case when vat_percent = 0 then 0
              when s.prices_include_vat then amount - floor(amount * 100.0 / (100 + vat_percent) + 0.5)::bigint
              else floor(amount * vat_percent / 100.0 + 0.5)::bigint end as vat
  from b;

  select sum(net), sum(vat) into v_net, v_vat from _inv_bands;
  if v_net + v_vat <= 0 then
    raise exception 'The total must be more than zero.';
  end if;

  if p_kind = 'credit_note' then
    select coalesce(sum(gross_pence), 0) into v_credited
      from public.invoices where credit_for_id = v_original.id;
    if v_credited + v_net + v_vat > v_original.gross_pence then
      raise exception 'The credit notes would be more than the invoice (%).', v_original.number;
    end if;
  end if;

  if p_kind = 'invoice' then
    update public.business_settings
      set next_invoice_number = next_invoice_number + 1
      where organisation_id = v_org
      returning invoice_prefix, next_invoice_number - 1 into v_prefix, v_seq;
  else
    update public.business_settings
      set next_credit_number = next_credit_number + 1
      where organisation_id = v_org
      returning credit_prefix, next_credit_number - 1 into v_prefix, v_seq;
  end if;
  v_number := v_prefix || lpad(v_seq::text, 5, '0');

  select nullif(trim(coalesce(c.first_name, '') || ' ' || coalesce(c.last_name, '')), '')
    into v_customer from public.contacts c where c.id = o.contact_id;

  insert into public.invoices (
    organisation_id, kind, number, order_id, order_reference, order_summary, order_note,
    credit_for_id, contact_id, customer_name, customer_address, issue_date, tax_point, due_date,
    supplier_name, supplier_address, supplier_vat_number, vat_registered, prices_include_vat,
    net_pence, vat_pence, gross_pence, note, created_by
  ) values (
    v_org, p_kind, v_number, o.id, o.reference, o.product_summary, nullif(trim(o.notes), ''),
    case when p_kind = 'credit_note' then v_original.id end, o.contact_id, v_customer,
    nullif(trim(o.delivery_address), ''), p_issue_date, p_issue_date,
    coalesce(p_due_date, p_issue_date),
    coalesce(nullif(trim(s.legal_name), ''), trim(s.trading_name)), nullif(trim(s.address), ''),
    case when s.vat_registered then s.vat_number end, s.vat_registered, s.prices_include_vat,
    v_net, v_vat, v_net + v_vat, nullif(trim(p_note), ''), v_staff
  ) returning id into v_id;

  insert into public.invoice_lines (
    invoice_id, organisation_id, position, description, quantity, unit_amount_pence,
    vat_code, vat_percent, net_pence, vat_pence, gross_pence
  )
  with cum as (
    select l.*, b.amount as band_amount, b.net as band_net, b.vat as band_vat,
           sum(l.amount) over (partition by l.vat_code order by l.pos) as cum_after,
           sum(l.amount) over (partition by l.vat_code order by l.pos) - l.amount as cum_before
    from _inv_lines l join _inv_bands b on b.vat_code = l.vat_code
  ), alloc as (
    select *,
      case when band_amount = 0 then 0 else
        floor(cum_after * band_net::numeric / band_amount + 0.5)::bigint
        - floor(cum_before * band_net::numeric / band_amount + 0.5)::bigint end as line_net,
      case when band_amount = 0 then 0 else
        floor(cum_after * band_vat::numeric / band_amount + 0.5)::bigint
        - floor(cum_before * band_vat::numeric / band_amount + 0.5)::bigint end as line_vat
    from cum
  )
  select v_id, v_org, pos, description, quantity, unit_amount_pence, vat_code, vat_percent,
         line_net, line_vat, line_net + line_vat
  from alloc order by pos;

  drop table _inv_lines;
  drop table _inv_bands;
  return v_id;
end;
$$;

revoke all on function public.issue_invoice(bigint, text, bigint, jsonb, date, date, text) from public, anon;
grant execute on function public.issue_invoice(bigint, text, bigint, jsonb, date, date, text) to authenticated;
