create table public.bills (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  supplier_name text not null check (char_length(trim(supplier_name)) > 0),
  supplier_vat_number text,
  reference text,
  bill_date date not null,
  due_date date,
  category text not null references public.expense_categories (code),
  description text not null check (char_length(trim(description)) > 0),
  order_id bigint references public.orders (id) on delete set null,
  vat_code text not null default 'S' references public.vat_rates (code),
  net_pence bigint not null check (net_pence >= 0),
  vat_pence bigint not null default 0 check (vat_pence >= 0),
  gross_pence bigint generated always as (net_pence + vat_pence) stored,
  vat_reclaimable boolean not null default true,
  paid_date date,
  payment_method text check (payment_method in ('cash', 'card', 'bank_transfer')),
  receipt_path text,
  note text,
  voided_at timestamptz,
  void_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bills_vat_within_net check (vat_pence <= net_pence),
  constraint bills_void_has_reason check (voided_at is null or void_reason is not null)
);
create index bills_org_date_idx on public.bills (organisation_id, bill_date desc);
create index bills_order_idx on public.bills (order_id);

create or replace function private.bills_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null then
      raise exception 'Only staff can add bills.' using errcode = '42501';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.updated_at := now();
  end if;
  if new.order_id is not null and not exists (
    select 1 from public.orders o where o.id = new.order_id and o.organisation_id = new.organisation_id
  ) then
    raise exception 'That order belongs to another business.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.bills_before_write() from public, anon, authenticated;

create trigger "10_bills_before_write"
  before insert or update on public.bills
  for each row execute function private.bills_before_write();
create trigger "90_bills_audit"
  after insert or update or delete on public.bills
  for each row execute function private.audit_row();

alter table public.bills enable row level security;

create policy "staff read their bills" on public.bills
  for select to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) is not null
  );
create policy "staff add bills" on public.bills
  for insert to authenticated
  with check ((select public.staff_role()) is not null);
create policy "staff change their bills" on public.bills
  for update to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) is not null
  )
  with check (organisation_id = (select private.current_organisation()));

revoke all on public.bills from anon, authenticated;
grant select on public.bills to authenticated;
