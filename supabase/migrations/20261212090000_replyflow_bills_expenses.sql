-- Supplier bills and expenses, per business, with the VAT on them (input VAT).
--
-- A bill can be linked to an order, which makes it a cost of that order and gives a margin per
-- order. Bills are never deleted: a wrong one is voided with a reason, so the history stays
-- complete. Every change is written to the audit log. The organisation and the person who
-- entered a bill are set by the database, never taken from the browser.
-- VAT is only ever reclaimed by a business that is VAT registered; that is decided when the
-- figures are worked out, not stored here, so switching VAT on later does not need old bills
-- to be changed.

create table public.expense_categories (
  code text primary key,
  label text not null,
  sort smallint not null
);

