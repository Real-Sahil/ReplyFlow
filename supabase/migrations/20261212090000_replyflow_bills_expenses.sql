  receipt_path, note, voided_at, void_reason
) on public.bills to authenticated;
grant all on public.bills to service_role;

-- One row per bill for the list and the export. The order's reference, what it is for and its
-- note are read live, so a bill always names the order it belongs to.
create view public.bill_ledger
  with (security_invoker = on)
  as
select
  b.id,
  b.bill_date,
  b.due_date,
  b.supplier_name,
  b.supplier_vat_number,
  b.reference,
  b.category,
  ec.label as category_label,
  b.description,
  b.note,
  b.order_id,
  o.reference as order_reference,
  o.product_summary as order_summary,
  o.notes as order_note,
  b.vat_code,
  b.net_pence,
  b.vat_pence,
  b.gross_pence,
  b.vat_reclaimable,
  b.paid_date,
  b.payment_method,
  b.receipt_path,
  b.voided_at,
  b.void_reason,
  case when b.voided_at is not null then 'void'
       when b.paid_date is not null then 'paid'
       else 'unpaid' end as status
from public.bills b
join public.expense_categories ec on ec.code = b.category
left join public.orders o on o.id = b.order_id;

grant select on public.bill_ledger to authenticated;
grant select on public.bill_ledger to service_role;
