-- Product catalogue (imported from the public website, then maintained here).

begin;

create table public.products (
    id bigint generated by default as identity primary key,
    reference text not null,
    title text not null,
    collection text,
    product_type text,
    colour text,
    description text,
    price_pence integer check (price_pence is null or price_pence >= 0),
    original_price_pence integer check (original_price_pence is null or original_price_pence >= 0),
    image_url text,
    images jsonb not null default '[]'::jsonb check (jsonb_typeof(images) = 'array'),
    source_url text,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index products_reference_key on public.products (lower(reference));
create index products_collection_idx on public.products (collection);

create trigger "10_products_set_updated_at"
    before update on public.products
    for each row execute function public.set_updated_at();

alter table public.orders
    add column product_id bigint references public.products (id) on delete set null;
create index orders_product_id_idx on public.orders (product_id);

alter table public.products enable row level security;

create policy "staff read" on public.products
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "agents insert" on public.products
    for insert to authenticated with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "agents update" on public.products
    for update to authenticated
    using ((select public.staff_role()) in ('admin', 'agent'))
    with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "admins delete" on public.products
    for delete to authenticated using ((select public.is_admin()));

grant select, insert, update, delete on public.products to authenticated;
grant all on public.products to service_role;

commit;
