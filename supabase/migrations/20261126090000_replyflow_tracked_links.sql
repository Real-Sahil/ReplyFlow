-- Tracked links. Each link sends people to a product page on the Mere & Row website and
-- counts the click. The link carries a campaign name (utm_campaign), which is kept on any
-- website enquiry that comes from a page reached through it, so sales can be traced back
-- to the post or campaign that brought them in.

create table public.tracked_links (
    code text primary key check (code ~ '^[a-z0-9]{8}$'),
    target_url text not null check (target_url ~ '^https://'),
    product_id bigint references public.products (id) on delete set null,
    utm_campaign text not null check (utm_campaign ~ '^[a-z0-9][a-z0-9-]{0,59}$'),
    created_by bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now()
);

create table public.link_clicks (
    id bigint generated by default as identity primary key,
    code text not null references public.tracked_links (code) on delete cascade,
    clicked_at timestamptz not null default now()
);
create index link_clicks_code_idx on public.link_clicks (code, clicked_at);

alter table public.tracked_links enable row level security;
create policy "staff read" on public.tracked_links
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "staff create" on public.tracked_links
    for insert to authenticated with check ((select public.staff_role()) is not null);
grant select, insert on public.tracked_links to authenticated;
grant all on public.tracked_links to service_role;

alter table public.link_clicks enable row level security;
create policy "staff read" on public.link_clicks
    for select to authenticated using ((select public.staff_role()) is not null);
grant select on public.link_clicks to authenticated;
grant all on public.link_clicks to service_role;

-- The campaign an enquiry came from, taken from the page address the form was sent from.
alter table public.deals add column campaign text;

-- Same as before, plus the campaign. Only the lines that set the campaign are new.
create or replace function public.record_web_enquiry(
    p_name text,
    p_email text,
    p_phone text,
    p_message text,
    p_product text,
    p_source_url text
) returns bigint
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_email text := lower(trim(coalesce(p_email, '')));
    v_phone text := nullif(trim(coalesce(p_phone, '')), '');
    v_name text := trim(coalesce(p_name, ''));
    v_first text;
    v_last text;
    v_contact_id bigint;
    v_deal_id bigint;
    v_note text;
begin
    v_first := split_part(v_name, ' ', 1);
    v_last := nullif(trim(substr(v_name, length(v_first) + 1)), '');

    if v_email <> '' then
        select c.id into v_contact_id
        from public.contacts c
        where exists (
            select 1 from jsonb_array_elements(coalesce(c.email_jsonb, '[]'::jsonb)) e
            where lower(e->>'email') = v_email
        )
        limit 1;
    end if;

    if v_contact_id is null then
        insert into public.contacts (first_name, last_name, email_jsonb, phone_jsonb, first_seen, last_seen)
        values (
            v_first,
            v_last,
            case when v_email <> '' then jsonb_build_array(jsonb_build_object('email', v_email, 'type', 'Work')) else '[]'::jsonb end,
            case when v_phone is not null then jsonb_build_array(jsonb_build_object('number', v_phone, 'type', 'Mobile')) else '[]'::jsonb end,
            now(),
            now()
        )
        returning id into v_contact_id;
    end if;

    v_note := left(
        'Website enquiry' ||
        coalesce(' about ' || nullif(trim(p_product), ''), '') ||
        coalesce(' from ' || nullif(trim(p_source_url), ''), '') ||
        E'\n' || coalesce(p_message, ''),
        4000
    );

    -- A repeat enquiry from the same person within a day joins the open deal.
    select d.id into v_deal_id
    from public.deals d
    where d.contact_ids @> array[v_contact_id]
      and d.archived_at is null
      and d.created_at > now() - interval '1 day'
    order by d.created_at desc
    limit 1;

    if v_deal_id is null then
        insert into public.deals (name, contact_ids, stage, description)
        values (
            'Website enquiry: ' || coalesce(nullif(trim(p_product), ''), 'general'),
            array[v_contact_id],
            'opportunity',
            left(coalesce(p_message, ''), 2000)
        )
        returning id into v_deal_id;
    end if;

    -- The campaign is set by the first enquiry that carries one.
    update public.deals
    set campaign = nullif(substring(coalesce(p_source_url, '') from 'utm_campaign=([A-Za-z0-9_-]+)'), '')
    where id = v_deal_id and campaign is null;

    insert into public.deal_notes (deal_id, text)
    values (v_deal_id, v_note);

    return v_deal_id;
end;
$$;

revoke execute on function public.record_web_enquiry(text, text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.record_web_enquiry(text, text, text, text, text, text) to service_role;
