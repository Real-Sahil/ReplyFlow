-- Destinations: one post going to one channel (see docs/SOCIAL_WORKFLOW.md). LinkedIn first; Facebook stays the
-- post's main destination through page_posts until it moves in as a destination too.

create table public.post_destinations (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id),
    post_id bigint not null references public.page_posts (id) on delete cascade,
    -- 'linkedin:page:<number>' or 'linkedin:profile:<sale id>' (and later 'facebook:page:<id>').
    channel_key text not null,
    -- Whose token posts a profile destination (the person whose profile it is). Null for a Page.
    owner_sale_id bigint references public.sales (id),
    -- Words for this destination only; null means the post's own words.
    text_override text check (text_override is null or (length(trim(text_override)) > 0 and length(text_override) <= 3000)),
    scheduled_for timestamptz,
    state text not null default 'planned'
        check (state in ('planned', 'scheduled', 'published', 'failed', 'removed')),
    external_id text,
    error text,
    posted_at timestamptz,
    created_by bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (post_id, channel_key),
    constraint post_destinations_schedule_check check (state <> 'scheduled' or scheduled_for is not null)
);
create index post_destinations_organisation_idx on public.post_destinations (organisation_id, post_id);
create index post_destinations_due_idx on public.post_destinations (scheduled_for) where state = 'scheduled';

create trigger "10_post_destinations_set_updated_at"
    before update on public.post_destinations
    for each row execute function public.set_updated_at();

-- Checks every write from a signed-in person: the post is theirs, the channel is connected to the business, a
-- profile is the writer's own, and a failed destination that is tried again forgets its old error. The server
-- (no signed-in person) is not held to these.
create or replace function private.post_destinations_before_write() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_org bigint;
    v_status text;
    v_parts text[];
begin
    select organisation_id, status into v_org, v_status from public.page_posts where id = new.post_id;
    if v_org is null then
        raise exception 'That post was not found' using errcode = '42501';
    end if;
    new.organisation_id := v_org;

    if private.staff_id() is not null then
        if v_org <> private.current_organisation() then
            raise exception 'That post belongs to another business' using errcode = '42501';
        end if;
        if tg_op = 'UPDATE' and new.channel_key is distinct from old.channel_key then
            raise exception 'A destination cannot change channel' using errcode = '42501';
        end if;
        v_parts := string_to_array(new.channel_key, ':');
        if v_parts[1] = 'linkedin' and v_parts[2] = 'page' then
            if not exists (
                select 1 from public.linkedin_pages
                 where organisation_id = v_org and org_id = v_parts[3]
            ) then
                raise exception 'That LinkedIn Page is not connected' using errcode = '42501';
            end if;
            new.owner_sale_id := null;
        elsif v_parts[1] = 'linkedin' and v_parts[2] = 'profile' then
            if v_parts[3] is distinct from private.staff_id()::text then
                raise exception 'You can post only to your own LinkedIn profile' using errcode = '42501';
            end if;
            new.owner_sale_id := private.staff_id();
        else
            raise exception 'That channel is not available' using errcode = '22023';
        end if;
        -- A version of the words is part of what an administrator approves. Once a post is approved, only an
        -- administrator may add or change one, so nothing unseen goes out under the business's name.
        if new.text_override is not null
           and (tg_op = 'INSERT' or new.text_override is distinct from old.text_override)
           and v_status in ('approved', 'scheduled', 'published')
           and not private.is_admin() then
            raise exception 'Only an administrator can change the words of an approved post' using errcode = '42501';
        end if;
        if tg_op = 'INSERT' then
            new.created_by := private.staff_id();
        end if;
        if tg_op = 'UPDATE' and old.state = 'failed' and new.state in ('planned', 'scheduled') then
            new.error := null;
        end if;
        if new.state = 'planned' then
            new.scheduled_for := null;
        end if;
    end if;
    return new;
end;
$$;
revoke execute on function private.post_destinations_before_write() from public, anon, authenticated;
create trigger "20_post_destinations_before_write"
    before insert or update on public.post_destinations
    for each row execute function private.post_destinations_before_write();
create trigger "90_post_destinations_audit"
    after insert or update or delete on public.post_destinations
    for each row execute function private.audit_row();

alter table public.post_destinations enable row level security;

create policy "members read their organisation destinations" on public.post_destinations
    for select to authenticated
    using (organisation_id = (select private.current_organisation()));

-- Staff choose destinations while the post can still be edited (the same rule as the post itself).
create policy "staff add destinations" on public.post_destinations
    for insert to authenticated
    with check (
        (select private.staff_role()) in ('admin', 'agent')
        and organisation_id = (select private.current_organisation())
        and state in ('planned', 'scheduled')
        and exists (
            select 1 from public.page_posts p
             where p.id = post_id
               and p.status in ('draft', 'pending_review', 'approved', 'failed', 'scheduled', 'published')
        )
    );
create policy "staff change destinations" on public.post_destinations
    for update to authenticated
    using (
        (select private.staff_role()) in ('admin', 'agent')
        and organisation_id = (select private.current_organisation())
        and state in ('planned', 'scheduled', 'failed', 'removed')
    )
    with check (
        organisation_id = (select private.current_organisation())
        and state in ('planned', 'scheduled')
    );
create policy "staff remove destinations" on public.post_destinations
    for delete to authenticated
    using (
        (select private.staff_role()) in ('admin', 'agent')
        and organisation_id = (select private.current_organisation())
        and state in ('planned', 'scheduled', 'failed', 'removed')
    );

revoke all on public.post_destinations from public, anon, authenticated;
grant select, delete on public.post_destinations to authenticated;
grant insert (post_id, channel_key, text_override, scheduled_for, state) on public.post_destinations to authenticated;
grant update (text_override, scheduled_for, state) on public.post_destinations to authenticated;
grant all on public.post_destinations to service_role;

-- Every channel the signed-in person can use, from every platform, in one list. A LinkedIn profile is listed for
-- its owner only (the table's own policy), and Facebook Pages carry whether they are the default.
create or replace view public.social_channels with (security_invoker = true) as
    select 'facebook:page:' || page_id as channel_key,
           'facebook'::text as platform,
           'page'::text as kind,
           page_id as external_id,
           name,
           null::timestamptz as expires_at,
           is_default,
           organisation_id
      from public.meta_pages_list
    union all
    select 'linkedin:page:' || org_id, 'linkedin', 'page', org_id, name, expires_at, false, organisation_id
      from public.linkedin_pages
    union all
    select 'linkedin:profile:' || sale_id, 'linkedin', 'profile', member_id, name, expires_at, false, organisation_id
      from public.linkedin_members;
grant select on public.social_channels to authenticated;

-- Bring across what was already posted to LinkedIn, so nothing is lost when the new records take over.
insert into public.post_destinations
    (organisation_id, post_id, channel_key, owner_sale_id, state, external_id, posted_at)
select organisation_id, post_id, 'linkedin:profile:' || sale_id, sale_id,
       case when removed_at is null then 'published' else 'removed' end, urn, posted_at
  from public.linkedin_posts
on conflict (post_id, channel_key) do nothing;

insert into public.post_destinations
    (organisation_id, post_id, channel_key, owner_sale_id, state, external_id, posted_at, created_by)
select organisation_id, post_id, 'linkedin:page:' || org_id, null,
       case when removed_at is null then 'published' else 'removed' end, urn, posted_at, posted_by
  from public.linkedin_page_posts
on conflict (post_id, channel_key) do nothing;

