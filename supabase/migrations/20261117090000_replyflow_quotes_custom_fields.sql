-- Quotes for a deal, and custom fields that each pipeline (deal category) adds to its deals.

create sequence public.quote_number_seq;

create table public.quotes (
    id bigint generated by default as identity primary key,
    quote_number text not null unique default
        'Q-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.quote_number_seq')::text, 4, '0'),
    deal_id bigint not null references public.deals (id) on delete cascade,
    status text not null default 'draft' check (status in ('draft', 'sent', 'accepted', 'declined')),
    -- Each line: {"description": text, "quantity": int, "unit_price_pence": int}
    lines jsonb not null default '[]'::jsonb check (jsonb_typeof(lines) = 'array'),
    discount_percent numeric(5, 2) not null default 0 check (discount_percent between 0 and 100),
    vat_percent numeric(5, 2) not null default 20 check (vat_percent between 0 and 100),
    valid_until date not null default (current_date + 30),
    notes text,
    sales_id bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index quotes_deal_idx on public.quotes (deal_id, created_at desc);

alter table public.quotes enable row level security;
create policy "staff read" on public.quotes
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "staff write" on public.quotes
    for insert to authenticated with check ((select public.staff_role()) is not null);
create policy "staff update" on public.quotes
    for update to authenticated
    using ((select public.staff_role()) is not null)
    with check ((select public.staff_role()) is not null);
grant select, insert, update on public.quotes to authenticated;
grant all on public.quotes to service_role;
grant usage, select on sequence public.quote_number_seq to authenticated, service_role;

create table public.custom_field_definitions (
    id bigint generated by default as identity primary key,
    -- The deal category this field belongs to, e.g. 'consumer-discretionary'.
    pipeline text not null,
    field_key text not null check (field_key ~ '^[a-z][a-z0-9_]*$'),
    label text not null,
    field_type text not null check (field_type in ('text', 'number', 'date', 'select')),
    options jsonb not null default '[]'::jsonb check (jsonb_typeof(options) = 'array'),
    position integer not null default 0,
    created_at timestamptz not null default now(),
    unique (pipeline, field_key)
);

alter table public.custom_field_definitions enable row level security;
create policy "staff read" on public.custom_field_definitions
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "administrators write" on public.custom_field_definitions
    for all to authenticated
    using (exists (select 1 from public.sales s where s.user_id = auth.uid() and s.administrator = true))
    with check (exists (select 1 from public.sales s where s.user_id = auth.uid() and s.administrator = true));
grant select on public.custom_field_definitions to authenticated;
grant all on public.custom_field_definitions to service_role;

alter table public.deals add column custom_fields jsonb not null default '{}'::jsonb
    check (jsonb_typeof(custom_fields) = 'object');
