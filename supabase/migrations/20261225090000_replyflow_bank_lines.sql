-- Bank statement lines, imported from a CSV the bank provides, so each can be matched to an invoice
-- payment, a supplier bill or a money-book entry. Nothing here talks to a bank. A line is never
-- deleted: it is matched, ignored or left open, and every change is audited.
--
-- amount_pence is signed: money in is positive, money out is negative. line_hash stops the same
-- line being imported twice when statements overlap.

create table public.bank_lines (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  line_date date not null,
  description text not null check (char_length(trim(description)) >= 1),
  amount_pence bigint not null check (amount_pence <> 0),
  line_hash text not null,
  status text not null default 'open' check (status in ('open', 'matched', 'ignored')),
  bill_id bigint references public.bills (id) on delete set null,
  order_payment_id bigint references public.order_payments (id) on delete set null,
  money_entry_id bigint references public.money_entries (id) on delete set null,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organisation_id, line_hash)
);
create index bank_lines_org_date_idx on public.bank_lines (organisation_id, line_date desc);
create index bank_lines_status_idx on public.bank_lines (organisation_id, status);
create index bank_lines_created_by_idx on public.bank_lines (created_by);
create index bank_lines_bill_idx on public.bank_lines (bill_id);
create index bank_lines_payment_idx on public.bank_lines (order_payment_id);
create index bank_lines_entry_idx on public.bank_lines (money_entry_id);

create or replace function private.bank_lines_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null then
      raise exception 'Only staff can import bank lines.' using errcode = '42501';
    end if;
  else
    -- Only the match can change; what the bank said never does.
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.line_date := old.line_date;
    new.description := old.description;
    new.amount_pence := old.amount_pence;
    new.line_hash := old.line_hash;
    new.updated_at := now();
  end if;
  if new.bill_id is not null and not exists (
    select 1 from public.bills b where b.id = new.bill_id and b.organisation_id = new.organisation_id
  ) then
    raise exception 'That bill belongs to another business.' using errcode = '42501';
  end if;
  if new.order_payment_id is not null and not exists (
    select 1 from public.order_payments p where p.id = new.order_payment_id and p.organisation_id = new.organisation_id
  ) then
    raise exception 'That payment belongs to another business.' using errcode = '42501';
  end if;
  if new.money_entry_id is not null and not exists (
    select 1 from public.money_entries e where e.id = new.money_entry_id and e.organisation_id = new.organisation_id
  ) then
    raise exception 'That entry belongs to another business.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.bank_lines_before_write() from public, anon, authenticated;

create trigger "10_bank_lines_before_write"
  before insert or update on public.bank_lines
  for each row execute function private.bank_lines_before_write();
create trigger "90_bank_lines_audit"
  after insert or update or delete on public.bank_lines
  for each row execute function private.audit_row();

alter table public.bank_lines enable row level security;
create policy "staff read their bank lines" on public.bank_lines
  for select to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) in ('admin', 'agent')
  );
create policy "staff import bank lines" on public.bank_lines
  for insert to authenticated
  with check (
    (select public.staff_role()) in ('admin', 'agent')
    and organisation_id = (select private.current_organisation())
  );
create policy "staff match their bank lines" on public.bank_lines
  for update to authenticated
  using (
    organisation_id = (select private.current_organisation())
    and (select public.staff_role()) in ('admin', 'agent')
  )
  with check (organisation_id = (select private.current_organisation()));

grant select on public.bank_lines to authenticated;
grant insert (line_date, description, amount_pence, line_hash) on public.bank_lines to authenticated;
grant update (status, bill_id, order_payment_id, money_entry_id, note) on public.bank_lines to authenticated;
grant all on public.bank_lines to service_role;
