-- Recurring entries and bills: rent, subscriptions, insurance, retainers and loan payments that repeat.
--
-- An administrator sets one up once. Every day the database adds the occurrences coming up in the next
-- 40 days as ordinary PLANNED money-book entries (money in or out) or UNPAID bills, so they show in the
-- money book, in what is owed and in the cash-flow view, and are marked done or paid by hand like any
-- other. Nothing is deleted: an item is paused or given an end date. If an occurrence cannot be added
-- (for example the books are locked for that date) the item stops there and says why.
--
-- Recurring invoices are not generated: an invoice belongs to an order and carries its own lines, so a
-- retainer is set up here as expected money in, and the invoice is still issued from the order.

create table public.recurring_items (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  kind text not null check (kind in ('money_in', 'money_out', 'bill')),
  title text not null check (char_length(trim(title)) > 0 and char_length(title) <= 120),
  frequency text not null check (frequency in ('weekly', 'fortnightly', 'monthly', 'quarterly', 'yearly')),
  next_date date not null,
  anchor_day int not null check (anchor_day between 1 and 31),
  end_date date,
  -- money_categories.code for money in and out, expense_categories.code for a bill
  category text not null,
  -- the amount of a money entry, or the amount before VAT of a bill
  amount_pence bigint not null check (amount_pence > 0),
  vat_pence bigint not null default 0 check (vat_pence >= 0 and vat_pence <= amount_pence),
  counterparty text,
  payment_method text check (payment_method is null or payment_method in ('cash', 'card', 'bank_transfer', 'other')),
  note text,
  due_days int not null default 14 check (due_days between 0 and 120),
  active boolean not null default true,
  last_generated_on date,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index recurring_items_org_idx on public.recurring_items (organisation_id, active, next_date);
create index recurring_items_created_by_idx on public.recurring_items (created_by);

-- The date after p_from. Months keep the day they started on (31 Jan, 28 Feb, 31 Mar), not drift.
create or replace function private.next_occurrence(p_from date, p_freq text, p_anchor int)
returns date
language sql
immutable
set search_path = ''
as $$
  select case p_freq
    when 'weekly' then p_from + 7
    when 'fortnightly' then p_from + 14
    else (
      select make_date(
        extract(year from m)::int,
        extract(month from m)::int,
        least(p_anchor, extract(day from (m + interval '1 month - 1 day'))::int)
      )
      from (
        select (date_trunc('month', p_from)::date
          + case p_freq when 'monthly' then interval '1 month'
                        when 'quarterly' then interval '3 months'
                        else interval '12 months' end)::date as m
      ) x
    )
  end
$$;

create or replace function private.recurring_items_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null or not private.is_admin() then
      raise exception 'Only an administrator can set up a repeating item.' using errcode = '42501';
    end if;
    new.anchor_day := extract(day from new.next_date)::int;
    new.last_generated_on := null;
    new.last_error := null;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.updated_at := now();
    -- What repeats and when it starts cannot be rewritten: end it and start another.
    new.kind := old.kind;
    new.frequency := old.frequency;
    new.anchor_day := old.anchor_day;
    new.category := old.category;
    if new.next_date is distinct from old.next_date and not private.is_admin() then
      new.next_date := old.next_date;
    end if;
    if new.active and not old.active then
      new.last_error := null;
    end if;
  end if;
  if new.end_date is not null and new.end_date < new.next_date and tg_op = 'INSERT' then
    raise exception 'The end date is before the first date.';
  end if;
  if new.kind = 'bill' then
    if not exists (select 1 from public.expense_categories c where c.code = new.category) then
      raise exception 'That is not a bill category.';
    end if;
  else
    if not exists (
      select 1 from public.money_categories c
      where c.code = new.category
        and c.direction = case new.kind when 'money_in' then 'in' else 'out' end
        and (not c.admin_only or private.is_admin())
    ) then
      raise exception 'That category does not match money %.', case new.kind when 'money_in' then 'in' else 'out' end;
    end if;
  end if;
  return new;
end;
$$;
revoke execute on function private.recurring_items_before_write() from public, anon, authenticated;

create trigger "10_recurring_items_before_write" before insert or update on public.recurring_items
  for each row execute function private.recurring_items_before_write();
create trigger "90_recurring_items_audit" after insert or update or delete on public.recurring_items
  for each row execute function private.audit_row();

alter table public.recurring_items enable row level security;
create policy "administrators read repeating items" on public.recurring_items for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add repeating items" on public.recurring_items for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators change repeating items" on public.recurring_items for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()))
  with check (organisation_id = (select private.current_organisation()));
create policy "accountant reads repeating items" on public.recurring_items for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_accountant()));

grant select on public.recurring_items to authenticated;
grant insert (kind, title, frequency, next_date, end_date, category, amount_pence, vat_pence, counterparty, payment_method, note, due_days)
  on public.recurring_items to authenticated;
grant update (title, end_date, amount_pence, vat_pence, counterparty, payment_method, note, due_days, active)
  on public.recurring_items to authenticated;
grant all on public.recurring_items to service_role;

-- Adds the occurrences due up to p_horizon, for one business or (null) for all of them. Each occurrence is
-- added as the person who set the item up, so every rule of the money book and bills (the books lock, the
-- business and the author) applies exactly as if they had typed it. Returns how many were added.
create or replace function private.generate_recurring(p_org bigint, p_horizon date)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.recurring_items;
  v_user uuid;
  v_next date;
  v_made int := 0;
  v_added int;
  v_label text;
begin
  for r in
    select * from public.recurring_items
     where active and next_date <= p_horizon and (p_org is null or organisation_id = p_org)
     order by organisation_id, id
     for update skip locked
  loop
    -- The person who created it if they can still sign in, otherwise any administrator of the business.
    select s.user_id into v_user from public.sales s
     where s.id = r.created_by and not s.disabled and s.administrator limit 1;
    if v_user is null then
      select s.user_id into v_user from public.sales s
       where s.organisation_id = r.organisation_id and s.administrator and not s.disabled order by s.id limit 1;
    end if;
    if v_user is null then
      update public.recurring_items set last_error = 'No administrator can sign in to add this.' where id = r.id;
      continue;
    end if;
    perform set_config('request.jwt.claim.sub', v_user::text, true);
    perform set_config('request.jwt.claims', jsonb_build_object('sub', v_user, 'role', 'authenticated')::text, true);

    v_added := 0;
    while r.next_date <= p_horizon and (r.end_date is null or r.next_date <= r.end_date) loop
      begin
        if r.kind = 'bill' then
          insert into public.bills
            (supplier_name, bill_date, due_date, category, description, vat_code, net_pence, vat_pence, vat_reclaimable, note)
          values
            (coalesce(nullif(trim(r.counterparty), ''), r.title), r.next_date, r.next_date + r.due_days, r.category,
             r.title, case when r.vat_pence > 0 then 'S' else 'O' end, r.amount_pence, r.vat_pence, true, r.note);
        else
          v_label := coalesce(nullif(trim(r.note), ''), r.title);
          insert into public.money_entries
            (direction, category, status, entry_date, amount_pence, counterparty, payment_method, note)
          values
            (case r.kind when 'money_in' then 'in' else 'out' end, r.category, 'planned', r.next_date, r.amount_pence,
             nullif(trim(r.counterparty), ''), r.payment_method,
             case when char_length(v_label) >= 3 then v_label else r.title end);
        end if;
        v_added := v_added + 1;
        r.last_generated_on := r.next_date;
        r.next_date := private.next_occurrence(r.next_date, r.frequency, r.anchor_day);
        r.last_error := null;
      exception when others then
        r.last_error := 'Could not add the ' || to_char(r.next_date, 'DD Mon YYYY') || ' entry: ' || sqlerrm;
        exit;
      end;
    end loop;

    update public.recurring_items
       set next_date = r.next_date, last_generated_on = r.last_generated_on, last_error = r.last_error
     where id = r.id;
    v_made := v_made + v_added;
  end loop;
  return v_made;
end;
$$;
revoke execute on function private.generate_recurring(bigint, date) from public, anon, authenticated;
grant execute on function private.generate_recurring(bigint, date) to service_role;

-- An administrator adds the coming occurrences straight away (after setting an item up).
create or replace function public.generate_my_recurring()
returns int
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do this.' using errcode = '42501';
  end if;
  return private.generate_recurring(private.current_organisation(), current_date + 40);
end;
$$;
revoke execute on function public.generate_my_recurring() from public, anon;
grant execute on function public.generate_my_recurring() to authenticated;

