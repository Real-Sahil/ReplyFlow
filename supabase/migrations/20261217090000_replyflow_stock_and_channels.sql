-- Stock and production, and the sales channel of an order.
--
-- Businesses buy stock and use it to make what they sell. stock_items are the things held;
-- stock_movements record every purchase, use in production, wastage and count correction, each
-- with a required note. Using stock against an order gives that order a stock cost, so its margin
-- is real. The cost of a use is fixed when it is recorded, from the average price paid for that
-- item so far, so later purchases never change an old order's cost.
--
-- Movements are never edited or deleted: a wrong one is voided with a reason. The organisation and
-- the author are set by the database. Every change is audited.

alter table public.orders
  add column sales_channel text
    check (sales_channel in ('ecommerce', 'facebook', 'email', 'phone', 'in_person', 'other'));
grant insert (sales_channel) on public.orders to authenticated;
grant update (sales_channel) on public.orders to authenticated;

create table public.stock_items (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  name text not null check (char_length(trim(name)) > 0),
  sku text,
  unit text not null default 'each' check (char_length(trim(unit)) > 0),
  reorder_level numeric(12, 3) check (reorder_level is null or reorder_level >= 0),
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint stock_items_name_unique unique (organisation_id, name)
);

create table public.stock_movements (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  item_id bigint not null references public.stock_items (id) on delete restrict,
  kind text not null check (kind in ('purchase', 'use', 'adjustment', 'waste')),
  quantity_delta numeric(12, 3) not null check (quantity_delta <> 0),
  unit_cost_pence numeric(14, 4) not null default 0 check (unit_cost_pence >= 0),
  moved_on date not null,
  order_id bigint references public.orders (id) on delete set null,
  bill_id bigint references public.bills (id) on delete set null,
  note text not null check (char_length(trim(note)) >= 3),
  voided_at timestamptz,
  void_reason text,
  created_at timestamptz not null default now(),
  constraint stock_direction check (
    (kind = 'purchase' and quantity_delta > 0)
    or (kind in ('use', 'waste') and quantity_delta < 0)
    or kind = 'adjustment'
  ),
  constraint stock_void_has_reason check (voided_at is null or void_reason is not null)
);
create index stock_items_org_idx on public.stock_items (organisation_id);
create index stock_movements_item_idx on public.stock_movements (item_id, moved_on desc);
create index stock_movements_order_idx on public.stock_movements (order_id);
create index stock_movements_org_idx on public.stock_movements (organisation_id);

create or replace function private.stock_items_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null then
      raise exception 'Only staff can add stock items.' using errcode = '42501';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create or replace function private.stock_movements_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
declare
  v_item_org bigint;
  v_avg numeric;
begin
  if tg_op = 'UPDATE' then
    -- Only voiding is allowed. Nothing else about a movement can change.
    if (to_jsonb(new) - 'voided_at' - 'void_reason') is distinct from (to_jsonb(old) - 'voided_at' - 'void_reason') then
      raise exception 'A stock movement cannot be changed. Void it and add a new one.';
    end if;
    return new;
  end if;

  new.organisation_id := private.current_organisation();
  new.created_by := private.staff_id();
  if new.organisation_id is null then
    raise exception 'Only staff can record stock.' using errcode = '42501';
  end if;
  select organisation_id into v_item_org from public.stock_items where id = new.item_id;
  if v_item_org is distinct from new.organisation_id then
    raise exception 'That stock item belongs to another business.' using errcode = '42501';
  end if;
  if new.order_id is not null and not exists (
    select 1 from public.orders o where o.id = new.order_id and o.organisation_id = new.organisation_id
  ) then
    raise exception 'That order belongs to another business.' using errcode = '42501';
  end if;
  if new.bill_id is not null and not exists (
    select 1 from public.bills b where b.id = new.bill_id and b.organisation_id = new.organisation_id
  ) then
    raise exception 'That bill belongs to another business.' using errcode = '42501';
  end if;
  if new.kind <> 'purchase' then
    -- What is taken out is valued at the average price paid so far, fixed now.
    select coalesce(sum(m.quantity_delta * m.unit_cost_pence) / nullif(sum(m.quantity_delta), 0), 0)
      into v_avg
      from public.stock_movements m
      where m.item_id = new.item_id and m.kind = 'purchase' and m.voided_at is null;
    new.unit_cost_pence := coalesce(v_avg, 0);
  end if;
  return new;
end;
$$;
revoke execute on function private.stock_items_before_write(), private.stock_movements_before_write()
  from public, anon, authenticated;

create trigger "10_stock_items_before_write" before insert or update on public.stock_items
  for each row execute function private.stock_items_before_write();
create trigger "10_stock_movements_before_write" before insert or update on public.stock_movements
  for each row execute function private.stock_movements_before_write();
create trigger "90_stock_items_audit" after insert or update or delete on public.stock_items
  for each row execute function private.audit_row();
create trigger "90_stock_movements_audit" after insert or update or delete on public.stock_movements
  for each row execute function private.audit_row();

alter table public.stock_items enable row level security;
alter table public.stock_movements enable row level security;

create policy "staff read stock items" on public.stock_items for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) is not null);
create policy "staff add stock items" on public.stock_items for insert to authenticated
  with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "staff change stock items" on public.stock_items for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) in ('admin', 'agent'))
  with check (organisation_id = (select private.current_organisation()));

create policy "staff read stock movements" on public.stock_movements for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) is not null);
create policy "staff add stock movements" on public.stock_movements for insert to authenticated
  with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "staff void stock movements" on public.stock_movements for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select public.staff_role()) in ('admin', 'agent'))
  with check (organisation_id = (select private.current_organisation()));

revoke all on public.stock_items, public.stock_movements from anon, authenticated;
grant select on public.stock_items, public.stock_movements to authenticated;
grant insert (name, sku, unit, reorder_level, notes, active) on public.stock_items to authenticated;
grant update (name, sku, unit, reorder_level, notes, active) on public.stock_items to authenticated;
grant insert (item_id, kind, quantity_delta, unit_cost_pence, moved_on, order_id, bill_id, note)
  on public.stock_movements to authenticated;
grant update (voided_at, void_reason) on public.stock_movements to authenticated;
grant all on public.stock_items, public.stock_movements to service_role;

-- What is held, and what it is worth at the average price paid.
create view public.stock_levels
  with (security_invoker = on)
  as
select
  i.id, i.name, i.sku, i.unit, i.reorder_level, i.notes, i.active,
  coalesce(sum(m.quantity_delta) filter (where m.voided_at is null), 0) as on_hand,
  coalesce(
    sum(m.quantity_delta * m.unit_cost_pence) filter (where m.kind = 'purchase' and m.voided_at is null)
    / nullif(sum(m.quantity_delta) filter (where m.kind = 'purchase' and m.voided_at is null), 0),
    0) as average_cost_pence,
  max(m.moved_on) filter (where m.voided_at is null) as last_moved_on
from public.stock_items i
left join public.stock_movements m on m.item_id = i.id
group by i.id;

-- The stock an order used, valued when it was taken out.
create view public.order_stock_costs
  with (security_invoker = on)
  as
select
  m.order_id,
  round(sum(-m.quantity_delta * m.unit_cost_pence))::bigint as stock_cost_pence
from public.stock_movements m
where m.kind = 'use' and m.voided_at is null and m.order_id is not null
group by m.order_id;

grant select on public.stock_levels, public.order_stock_costs to authenticated;
grant select on public.stock_levels, public.order_stock_costs to service_role;
