-- Hours and holiday, from the staff sign-in.
--
-- The staff sign-in (the "claimant" role, created by an administrator and handed over in person) can already
-- send expense claims. It can now also record the hours it worked and ask for holiday. Each goes to the
-- administrator to approve or refuse. This is records only: it adds up hours and holiday and does not
-- calculate pay.
--
-- A staff sign-in can be linked to a person record in People (people.sales_id). When a holiday request is
-- approved for a linked person, it is also added to that person's leave, so their holiday allowance stays right.

alter table public.people add column sales_id bigint references public.sales (id) on delete set null;
create unique index people_sales_id_key on public.people (sales_id) where sales_id is not null;

create or replace function private.people_sales_link_check() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if new.sales_id is not null and not exists (
    select 1 from public.sales s where s.id = new.sales_id and s.organisation_id = new.organisation_id
  ) then
    raise exception 'That sign-in belongs to another business.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.people_sales_link_check() from public, anon, authenticated;
create trigger "20_people_sales_link_check" before insert or update on public.people
  for each row execute function private.people_sales_link_check();
grant insert (sales_id) on public.people to authenticated;
grant update (sales_id) on public.people to authenticated;

create table public.time_entries (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  staff_id bigint not null references public.sales (id),
  work_date date not null,
  hours numeric(4, 2) not null check (hours >= 0.25 and hours <= 24),
  note text check (note is null or char_length(note) <= 200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  decided_by bigint references public.sales (id) on delete set null,
  decided_at timestamptz,
  decision_note text,
  created_at timestamptz not null default now()
);
create index time_entries_org_idx on public.time_entries (organisation_id, status, work_date);
create index time_entries_staff_idx on public.time_entries (staff_id, work_date desc);
create index time_entries_decided_by_idx on public.time_entries (decided_by);

create table public.holiday_requests (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  staff_id bigint not null references public.sales (id),
  from_date date not null,
  to_date date not null,
  days numeric(4, 1) not null check (days > 0 and days <= 60),
  note text check (note is null or char_length(note) <= 200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  decided_by bigint references public.sales (id) on delete set null,
  decided_at timestamptz,
  decision_note text,
  created_at timestamptz not null default now(),
  constraint holiday_dates_order check (to_date >= from_date)
);
create index holiday_requests_org_idx on public.holiday_requests (organisation_id, status, from_date);
create index holiday_requests_staff_idx on public.holiday_requests (staff_id, from_date desc);
create index holiday_requests_decided_by_idx on public.holiday_requests (decided_by);

-- The business, the person and the status are set by the database, never by the sender.
create or replace function private.time_requests_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
declare
  v_staff bigint;
begin
  if tg_op = 'INSERT' then
    v_staff := private.staff_id();
    if v_staff is null or not private.is_claimant() then
      raise exception 'Only a staff sign-in can send this.' using errcode = '42501';
    end if;
    new.organisation_id := private.current_organisation();
    new.staff_id := v_staff;
    new.status := 'pending';
    new.decided_by := null;
    new.decided_at := null;
    new.decision_note := null;
    if tg_table_name = 'time_entries' then
      if new.work_date > current_date or new.work_date < current_date - 60 then
        raise exception 'Hours can be recorded for today or the last 60 days.';
      end if;
      if (select count(*) from public.time_entries e
           where e.staff_id = v_staff and e.created_at > now() - interval '24 hours') >= 50 then
        raise exception 'That is a lot of entries for one day. Please try again tomorrow.';
      end if;
    else
      if new.from_date < current_date - 31 or new.from_date > current_date + 400 then
        raise exception 'Holiday can start from the last month up to a year ahead.';
      end if;
      if (select count(*) from public.holiday_requests e
           where e.staff_id = v_staff and e.created_at > now() - interval '24 hours') >= 10 then
        raise exception 'That is a lot of requests for one day. Please try again tomorrow.';
      end if;
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.staff_id := old.staff_id;
  end if;
  return new;
end;
$$;
revoke execute on function private.time_requests_before_write() from public, anon, authenticated;

create trigger "10_time_entries_before_write" before insert or update on public.time_entries
  for each row execute function private.time_requests_before_write();
create trigger "10_holiday_requests_before_write" before insert or update on public.holiday_requests
  for each row execute function private.time_requests_before_write();
create trigger "90_time_entries_audit" after insert or update or delete on public.time_entries
  for each row execute function private.audit_row();
create trigger "90_holiday_requests_audit" after insert or update or delete on public.holiday_requests
  for each row execute function private.audit_row();

alter table public.time_entries enable row level security;
alter table public.holiday_requests enable row level security;

