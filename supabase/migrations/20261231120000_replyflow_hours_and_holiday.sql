-- Approve or refuse hours, one or several at once. A refusal needs a reason the person can read.
create or replace function public.decide_time_entries(p_ids bigint[], p_approve boolean, p_note text default null)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_n int;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can decide hours.' using errcode = '42501';
  end if;
  if not p_approve and char_length(trim(coalesce(p_note, ''))) = 0 then
    raise exception 'Please give a reason, so the person knows why.';
  end if;
  update public.time_entries
     set status = case when p_approve then 'approved' else 'rejected' end,
         decided_by = private.staff_id(), decided_at = now(),
         decision_note = nullif(trim(coalesce(p_note, '')), '')
   where id = any (p_ids) and organisation_id = private.current_organisation() and status = 'pending';
  get diagnostics v_n = row_count;
  return v_n;
end;
$$;

-- Approve or refuse holiday. An approved request for someone linked to a person record is also added to their
-- leave, so the holiday left of their allowance stays right.
create or replace function public.decide_holiday_request(p_id bigint, p_approve boolean, p_note text default null)
returns public.holiday_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.holiday_requests;
  v_person bigint;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can decide holiday.' using errcode = '42501';
  end if;
  select * into r from public.holiday_requests
   where id = p_id and organisation_id = private.current_organisation() for update;
  if not found then
    raise exception 'Request not found.';
  end if;
  if r.status <> 'pending' then
    raise exception 'That request has already been decided.';
  end if;
  if not p_approve and char_length(trim(coalesce(p_note, ''))) = 0 then
    raise exception 'Please give a reason, so the person knows why.';
  end if;
  update public.holiday_requests
     set status = case when p_approve then 'approved' else 'rejected' end,
         decided_by = private.staff_id(), decided_at = now(),
         decision_note = nullif(trim(coalesce(p_note, '')), '')
   where id = p_id
   returning * into r;
  if p_approve then
    select p.id into v_person from public.people p
     where p.sales_id = r.staff_id and p.organisation_id = r.organisation_id and p.active limit 1;
    if v_person is not null then
      insert into public.person_leave (person_id, kind, from_date, to_date, days, note)
      values (v_person, 'holiday', r.from_date, r.to_date, r.days, coalesce(r.note, 'Approved request'));
    end if;
  end if;
  return r;
end;
$$;

revoke execute on function public.decide_time_entries(bigint[], boolean, text) from public, anon;
revoke execute on function public.decide_holiday_request(bigint, boolean, text) from public, anon;
grant execute on function public.decide_time_entries(bigint[], boolean, text) to authenticated, service_role;
grant execute on function public.decide_holiday_request(bigint, boolean, text) to authenticated, service_role;

