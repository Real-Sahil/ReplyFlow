-- Unified Messenger inbox and saved replies.

alter table public.contacts add column messenger_read_at timestamptz;

-- One row per Messenger conversation, newest first in the app. Runs with the
-- caller's permissions, so the contact and message policies still apply.
create view public.messenger_inbox
    with (security_invoker = on)
    as
select
    c.id as id,
    c.id as contact_id,
    c.first_name,
    c.last_name,
    c.sales_id,
    c.messenger_read_at,
    lm.body as last_body,
    lm.direction as last_direction,
    lm.sent_at as last_sent_at,
    li.sent_at as last_inbound_at,
    (li.sent_at is not null and li.sent_at > now() - interval '24 hours') as window_open,
    (li.sent_at is not null and (c.messenger_read_at is null or li.sent_at > c.messenger_read_at)) as unread
from public.contacts c
join lateral (
    select m.body, m.direction, m.sent_at
    from public.messenger_messages m
    where m.contact_id = c.id
    order by m.sent_at desc
    limit 1
) lm on true
left join lateral (
    select m.sent_at
    from public.messenger_messages m
    where m.contact_id = c.id and m.direction = 'inbound'
    order by m.sent_at desc
    limit 1
) li on true;

grant select on public.messenger_inbox to authenticated;
grant all on public.messenger_inbox to service_role;

create table public.saved_replies (
    id bigint generated by default as identity primary key,
    title text not null check (length(trim(title)) > 0),
    body text not null check (length(trim(body)) > 0 and length(body) <= 2000),
    created_by bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create trigger "10_saved_replies_set_updated_at"
    before update on public.saved_replies
    for each row execute function public.set_updated_at();

alter table public.saved_replies enable row level security;
create policy "staff read" on public.saved_replies
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "agents insert" on public.saved_replies
    for insert to authenticated with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "agents update" on public.saved_replies
    for update to authenticated
    using ((select public.staff_role()) in ('admin', 'agent'))
    with check ((select public.staff_role()) in ('admin', 'agent'));
create policy "admins delete" on public.saved_replies
    for delete to authenticated using ((select public.is_admin()));

grant select, insert, update, delete on public.saved_replies to authenticated;
grant all on public.saved_replies to service_role;

