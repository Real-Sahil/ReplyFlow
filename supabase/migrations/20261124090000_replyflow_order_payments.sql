-- Payments on orders. Most orders are paid in cash on delivery; some take a deposit first,
-- and some ask for a refundable security deposit. Each payment is recorded as a row.
-- orders.paid_pence is worked out from the rows for the goods (deposit and balance), so it
-- can no longer be typed in. A security deposit is held against the order but is not payment
-- for the goods, so it never counts towards the balance.

-- VAT is not charged on quotes. quotes.vat_percent is unused (default 0). It is not dropped
-- here because DROP statements hang on this project; drop it when that is resolved.

alter table public.orders
    add column payment_terms text not null default 'cash_on_delivery'
        check (payment_terms in ('cash_on_delivery', 'deposit_first')),
    add column security_deposit_pence bigint not null default 0
        check (security_deposit_pence >= 0);

update public.orders set payment_terms = 'deposit_first' where deposit_required_pence > 0;

create table public.order_payments (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders (id) on delete cascade,
    kind text not null check (kind in ('deposit', 'balance', 'security_deposit', 'security_refund')),
    amount_pence bigint not null check (amount_pence > 0),
    method text not null check (method in ('cash', 'card', 'bank_transfer')),
    received_at timestamptz not null default now(),
    note text,
    sales_id bigint references public.sales (id) on delete set null,
    created_at timestamptz not null default now()
);
create index order_payments_order_idx on public.order_payments (order_id, received_at);

-- Payments that were typed into paid_pence before this change are kept as one row each.
insert into public.order_payments (order_id, kind, amount_pence, method, note)
select id,
       case when deposit_required_pence > 0 then 'deposit' else 'balance' end,
       paid_pence,
       'cash',
       'Recorded before payments were tracked. Method not recorded.'
from public.orders
where paid_pence > 0;

alter table public.order_payments enable row level security;
create policy "staff read" on public.order_payments
    for select to authenticated using ((select public.staff_role()) is not null);
create policy "staff record" on public.order_payments
    for insert to authenticated with check ((select public.staff_role()) is not null);
grant select, insert on public.order_payments to authenticated;
grant all on public.order_payments to service_role;

-- Append only: a mistake is corrected with a refund row, so the history stays complete.
create or replace function public.sync_order_paid() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
begin
    update public.orders o
    set paid_pence = coalesce((
        select sum(p.amount_pence) from public.order_payments p
        where p.order_id = o.id and p.kind in ('deposit', 'balance')
    ), 0)
    where o.id = new.order_id;
    return null;
end;
$$;

revoke execute on function public.sync_order_paid() from public, anon, authenticated;

create trigger "40_order_payments_sync_paid"
    after insert on public.order_payments
    for each row execute function public.sync_order_paid();

create trigger "90_order_payments_audit"
    after insert or delete or update on public.order_payments
    for each row execute function private.audit_row();

-- Bring paid_pence in line with the payment rows (the backfill above is the only source).
update public.orders o set paid_pence = coalesce((
    select sum(p.amount_pence) from public.order_payments p
    where p.order_id = o.id and p.kind in ('deposit', 'balance')
), 0);
