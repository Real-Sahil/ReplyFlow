-- The audit history of these tables carries pay rates and personal details, so, as for wages in the
-- money book, only administrators can read it. A restrictive rule is added on top of the existing one.
create policy "people history is for administrators" on public.audit_log
  as restrictive for select to authenticated
  using (table_name not in ('people', 'person_documents', 'person_leave') or (select private.is_admin()));
