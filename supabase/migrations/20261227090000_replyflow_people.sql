create policy "administrators read people" on public.people for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add people" on public.people for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators change people" on public.people for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()))
  with check (organisation_id = (select private.current_organisation()));

