-- People: the staff and contractors of a business, with their documents (right to work, licences,
-- insurance, certificates) and their holiday and absence. For administrators only: pay rates and
-- personal details are private. Nothing is deleted: a person is marked as no longer working here, a
-- document as no longer current, and a leave entry is voided. Every change is audited.
-- This keeps records and reminders. It does not run payroll.

create table public.people (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  full_name text not null check (char_length(trim(full_name)) > 0),
  kind text not null default 'employee' check (kind in ('employee', 'contractor')),
  role_title text,
  phone text,
  email text,
  start_date date,
  end_date date,
  pay_rate_pence bigint check (pay_rate_pence is null or pay_rate_pence >= 0),
  pay_basis text check (pay_basis is null or pay_basis in ('hour', 'day', 'week', 'month', 'year', 'job')),
  holiday_allowance_days numeric(5, 1) not null default 28 check (holiday_allowance_days >= 0),
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index people_org_idx on public.people (organisation_id, active);
create index people_created_by_idx on public.people (created_by);

create table public.person_documents (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  person_id bigint not null references public.people (id) on delete restrict,
  title text not null check (char_length(trim(title)) > 0),
  issued_on date,
  expires_on date,
  note text,
  file_path text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index person_documents_person_idx on public.person_documents (person_id);
create index person_documents_expiry_idx on public.person_documents (organisation_id, expires_on) where active;
create index person_documents_created_by_idx on public.person_documents (created_by);

create table public.person_leave (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  person_id bigint not null references public.people (id) on delete restrict,
  kind text not null default 'holiday' check (kind in ('holiday', 'sick', 'other')),
  from_date date not null,
  to_date date not null,
  days numeric(4, 1) not null check (days > 0),
  note text,
  voided_at timestamptz,
  created_at timestamptz not null default now(),
  constraint person_leave_dates check (to_date >= from_date)
);
create index person_leave_person_idx on public.person_leave (person_id, from_date);
create index person_leave_created_by_idx on public.person_leave (created_by);

-- The business and the author are set by the database, and a record can only point at a person of
-- the same business.
create or replace function private.people_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null then
      raise exception 'Only staff can add people.' using errcode = '42501';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    if tg_table_name <> 'person_leave' then
      new.updated_at := now();
    end if;
  end if;
  -- person_id is read through jsonb because the people table itself has no such column.
  if tg_table_name <> 'people' and not exists (
    select 1 from public.people p
    where p.id = (to_jsonb(new) ->> 'person_id')::bigint and p.organisation_id = new.organisation_id
  ) then
    raise exception 'That person belongs to another business.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.people_before_write() from public, anon, authenticated;

create trigger "10_people_before_write" before insert or update on public.people
  for each row execute function private.people_before_write();
create trigger "10_person_documents_before_write" before insert or update on public.person_documents
  for each row execute function private.people_before_write();
create trigger "10_person_leave_before_write" before insert or update on public.person_leave
  for each row execute function private.people_before_write();
create trigger "90_people_audit" after insert or update or delete on public.people
  for each row execute function private.audit_row();
create trigger "90_person_documents_audit" after insert or update or delete on public.person_documents
  for each row execute function private.audit_row();
create trigger "90_person_leave_audit" after insert or update or delete on public.person_leave
  for each row execute function private.audit_row();

