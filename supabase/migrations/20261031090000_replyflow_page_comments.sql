-- Comments on the business Page's posts (official Page feed webhook).

create table public.page_comments (
    id bigint generated by default as identity primary key,
    comment_id text not null unique,
    post_id text not null,
    parent_id text,
    page_id text not null,
    author_id text not null,
    author_name text,
    body text,
    commented_at timestamptz not null default now(),
    status text not null default 'new' check (status in ('new', 'replied', 'hidden', 'handled')),
    reply_text text,
    replied_by bigint references public.sales (id) on delete set null,
    replied_at timestamptz,
    private_reply_at timestamptz,
    contact_id bigint references public.contacts (id) on delete set null,
    created_at timestamptz not null default now()
);
create index page_comments_status_idx on public.page_comments (status, commented_at desc);

alter table public.page_comments enable row level security;
create policy "staff read" on public.page_comments
    for select to authenticated using ((select public.staff_role()) is not null);
grant select on public.page_comments to authenticated;
grant all on public.page_comments to service_role;

-- Stores a customer comment. Comments written by the Page itself are ignored, and
-- Meta redelivering the same comment returns null.
create or replace function public.record_page_comment(
    p_comment_id text,
    p_post_id text,
    p_parent_id text,
    p_page_id text,
    p_author_id text,
    p_author_name text,
    p_body text,
    p_commented_at timestamptz
) returns bigint
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_id bigint;
begin
    if p_author_id = p_page_id then
        return null;
    end if;
    insert into public.page_comments
        (comment_id, post_id, parent_id, page_id, author_id, author_name, body, commented_at)
    values
        (p_comment_id, p_post_id, p_parent_id, p_page_id, p_author_id, p_author_name,
         left(p_body, 4000), coalesce(p_commented_at, now()))
    on conflict (comment_id) do nothing
    returning id into v_id;
    return v_id;
end;
$$;

-- Turns a comment into a contact and an open enquiry. With a PSID (from a private
-- reply) the customer's later Messenger messages join the same contact.
create or replace function public.record_comment_lead(
    p_comment_row_id bigint,
    p_psid text
) returns bigint
    language plpgsql security definer
    set search_path = ''
    as $$
declare
    v_comment public.page_comments;
    v_contact_id bigint;
    v_deal_id bigint;
    v_name text;
begin
    select * into v_comment from public.page_comments where id = p_comment_row_id;
    if not found then
        raise exception 'comment not found';
    end if;

    v_contact_id := v_comment.contact_id;
    if v_contact_id is null and p_psid is not null then
        select id into v_contact_id from public.contacts where messenger_psid = p_psid;
    end if;

    if v_contact_id is null then
        v_name := coalesce(nullif(trim(v_comment.author_name), ''), 'Facebook commenter');
        insert into public.contacts (first_name, last_name, messenger_psid, first_seen, last_seen)
        values (
            split_part(v_name, ' ', 1),
            nullif(trim(substr(v_name, length(split_part(v_name, ' ', 1)) + 1)), ''),
            p_psid, now(), now())
        returning id into v_contact_id;
    elsif p_psid is not null then
        update public.contacts set messenger_psid = p_psid
        where id = v_contact_id and messenger_psid is null;
    end if;

    select d.id into v_deal_id
    from public.deals d
    where d.contact_ids @> array[v_contact_id]
      and d.archived_at is null and d.stage not in ('won', 'lost')
    order by d.created_at desc limit 1;

    if v_deal_id is null then
        insert into public.deals (name, stage, contact_ids, description, created_at, updated_at)
        values ('Facebook comment: ' || coalesce(nullif(trim(v_comment.author_name), ''), 'enquiry'),
                'opportunity', array[v_contact_id],
                'Comment on a Page post: ' || left(coalesce(v_comment.body, ''), 500), now(), now())
        returning id into v_deal_id;
    end if;

    update public.page_comments set contact_id = v_contact_id where id = p_comment_row_id;
    return v_contact_id;
end;
$$;

revoke execute on function
    public.record_page_comment(text, text, text, text, text, text, text, timestamptz),
    public.record_comment_lead(bigint, text)
    from public, anon, authenticated;
grant execute on function
    public.record_page_comment(text, text, text, text, text, text, text, timestamptz),
    public.record_comment_lead(bigint, text)
    to service_role;
