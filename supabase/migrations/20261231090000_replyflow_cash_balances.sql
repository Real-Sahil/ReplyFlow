-- The bank balance an administrator types in, as the starting point of the cash-flow view. Every time it is
-- updated a new row is added (nothing is overwritten or deleted), so the history of what was entered stays.

create table public.cash_balances (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  balance_pence bigint not null check (balance_pence between -100000000000 and 100000000000),
  as_at date not null,
  note text check (note is null or char_length(note) <= 200),
  created_at timestamptz not null default now()
);
create index cash_balances_org_idx on public.cash_balances (organisation_id, as_at desc, id desc);
create index cash_balances_created_by_idx on public.cash_balances (created_by);

create or replace function private.cash_balances_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op <> 'INSERT' then
    raise exception 'A saved balance cannot be changed. Enter a new one.' using errcode = '42501';
  end if;
  new.organisation_id := private.current_organisation();
  new.created_by := private.staff_id();
  if new.organisation_id is null or not private.is_admin() then
    raise exception 'Only an administrator can enter the balance.' using errcode = '42501';
  end if;
  if new.as_at > current_date + 1 then
    raise exception 'The date of the balance cannot be in the future.';
  end if;
  return new;
end;
$$;
revoke execute on function private.cash_balances_before_write() from public, anon, authenticated;

create trigger "10_cash_balances_before_write" before insert or update on public.cash_balances
  for each row execute function private.cash_balances_before_write();
create trigger "90_cash_balances_audit" after insert or update or delete on public.cash_balances
  for each row execute function private.audit_row();

alter table public.cash_balances enable row level security;
create policy "administrators read balances" on public.cash_balances for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add balances" on public.cash_balances for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "accountant reads balances" on public.cash_balances for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_accountant()));

grant select on public.cash_balances to authenticated;
grant insert (balance_pence, as_at, note) on public.cash_balances to authenticated;
grant all on public.cash_balances to service_role;
