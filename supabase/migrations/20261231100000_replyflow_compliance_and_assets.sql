-- Business paperwork with dates, and a register of equipment and vehicles.
--
-- BUSINESS DOCUMENTS: insurance, licences, certificates, safety checks, vehicle tests, contracts. Each can
-- carry an expiry date, a reference (policy or certificate number) and a copy of the file, and can be about
-- one item of equipment. The app reminds an administrator before they run out. (Staff documents live with
-- the person, in People.)
--
-- ASSETS: vans, tools, laptops and phones, with who holds them, what they cost and when they are next due a
-- service or test.
--
-- Administrators only, because cost and personal details are private. Nothing is deleted: a document is
-- marked no longer current, an item no longer in use. Every change is audited.

create table public.assets (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  name text not null check (char_length(trim(name)) > 0 and char_length(name) <= 120),
  kind text not null default 'equipment' check (kind in ('vehicle', 'tool', 'equipment', 'it', 'other')),
  identifier text check (identifier is null or char_length(identifier) <= 60),
  holder_person_id bigint references public.people (id) on delete set null,
  purchase_date date,
  cost_pence bigint check (cost_pence is null or cost_pence >= 0),
  last_service_date date,
  next_service_date date,
  service_every_months int check (service_every_months is null or service_every_months between 1 and 120),
  notes text check (notes is null or char_length(notes) <= 1000),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index assets_org_idx on public.assets (organisation_id, active);
create index assets_service_idx on public.assets (organisation_id, next_service_date) where active;
create index assets_holder_idx on public.assets (holder_person_id);
create index assets_created_by_idx on public.assets (created_by);

create table public.business_documents (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  title text not null check (char_length(trim(title)) > 0 and char_length(title) <= 120),
  category text not null default 'other'
    check (category in ('insurance', 'licence', 'certificate', 'safety', 'vehicle', 'contract', 'other')),
  asset_id bigint references public.assets (id) on delete set null,
  provider text check (provider is null or char_length(provider) <= 120),
  reference text check (reference is null or char_length(reference) <= 80),
  issued_on date,
  expires_on date,
  note text check (note is null or char_length(note) <= 1000),
  file_path text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index business_documents_org_idx on public.business_documents (organisation_id, active);
create index business_documents_expiry_idx on public.business_documents (organisation_id, expires_on) where active;
create index business_documents_asset_idx on public.business_documents (asset_id);
create index business_documents_created_by_idx on public.business_documents (created_by);

-- The business and the author are set by the database, and anything a record points at must belong to the
-- same business. A copy of a file must sit in this business's own folder.
create or replace function private.paperwork_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
declare
  v_holder bigint;
  v_asset bigint;
  v_file text;
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null or not private.is_admin() then
      raise exception 'Only an administrator can keep this.' using errcode = '42501';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.updated_at := now();
  end if;
  v_holder := (to_jsonb(new) ->> 'holder_person_id')::bigint;
  v_asset := (to_jsonb(new) ->> 'asset_id')::bigint;
  v_file := to_jsonb(new) ->> 'file_path';
  if v_holder is not null and not exists (
    select 1 from public.people p where p.id = v_holder and p.organisation_id = new.organisation_id
  ) then
    raise exception 'That person belongs to another business.' using errcode = '42501';
  end if;
  if v_asset is not null and not exists (
    select 1 from public.assets a where a.id = v_asset and a.organisation_id = new.organisation_id
  ) then
    raise exception 'That item belongs to another business.' using errcode = '42501';
  end if;
  if v_file is not null and v_file not like new.organisation_id::text || '/%' then
    raise exception 'The file must be in your own business folder.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke execute on function private.paperwork_before_write() from public, anon, authenticated;

create trigger "10_assets_before_write" before insert or update on public.assets
  for each row execute function private.paperwork_before_write();
create trigger "10_business_documents_before_write" before insert or update on public.business_documents
  for each row execute function private.paperwork_before_write();
create trigger "90_assets_audit" after insert or update or delete on public.assets
  for each row execute function private.audit_row();
create trigger "90_business_documents_audit" after insert or update or delete on public.business_documents
  for each row execute function private.audit_row();

alter table public.assets enable row level security;
alter table public.business_documents enable row level security;

create policy "administrators read assets" on public.assets for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add assets" on public.assets for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators change assets" on public.assets for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()))
  with check (organisation_id = (select private.current_organisation()));
create policy "accountant reads assets" on public.assets for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_accountant()));

create policy "administrators read business documents" on public.business_documents for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add business documents" on public.business_documents for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators change business documents" on public.business_documents for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()))
  with check (organisation_id = (select private.current_organisation()));

grant select on public.assets, public.business_documents to authenticated;
grant insert (name, kind, identifier, holder_person_id, purchase_date, cost_pence, last_service_date, next_service_date, service_every_months, notes, active)
  on public.assets to authenticated;
grant update (name, kind, identifier, holder_person_id, purchase_date, cost_pence, last_service_date, next_service_date, service_every_months, notes, active)
  on public.assets to authenticated;
grant insert (title, category, asset_id, provider, reference, issued_on, expires_on, note, file_path, active)
  on public.business_documents to authenticated;
grant update (title, category, asset_id, provider, reference, issued_on, expires_on, note, file_path, active)
  on public.business_documents to authenticated;
grant all on public.assets, public.business_documents to service_role;

-- The audit history of these carries costs, so, as for people and wages, only administrators read it.
create policy "paperwork history is for administrators" on public.audit_log
  as restrictive for select to authenticated
  using (table_name not in ('assets', 'business_documents') or (select private.is_admin()));
