-- Repeat an invoice: draft invoices for an administrator to confirm.
--
-- An administrator chooses "Repeat this invoice" on an issued invoice. The database keeps a copy of its lines
-- and, a week before each due date, adds a DRAFT invoice for the same order. A draft is not an invoice: it has
-- no number, counts for nothing in the books and is never sent. The administrator checks it (and can change
-- the lines or the date), then confirms, and only then is it issued through issue_invoice(), so numbering,
-- VAT, the books lock and the order checks are exactly those of an invoice made by hand. Or they dismiss it.
-- Nothing is deleted: a repeat is paused or given an end date, a draft is issued or dismissed.

create table public.recurring_invoices (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  created_by bigint references public.sales (id) on delete set null,
  source_invoice_id bigint not null references public.invoices (id) on delete restrict,
  order_id bigint not null references public.orders (id) on delete restrict,
  frequency text not null check (frequency in ('weekly', 'fortnightly', 'monthly', 'quarterly', 'yearly')),
  next_date date not null,
  anchor_day int not null check (anchor_day between 1 and 31),
  end_date date,
  due_days int not null default 14 check (due_days between 0 and 120),
  note text check (note is null or char_length(note) <= 500),
  lines jsonb not null,
  active boolean not null default true,
  last_generated_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index recurring_invoices_org_idx on public.recurring_invoices (organisation_id, active, next_date);
create index recurring_invoices_source_idx on public.recurring_invoices (source_invoice_id);
create index recurring_invoices_order_idx on public.recurring_invoices (order_id);
create index recurring_invoices_created_by_idx on public.recurring_invoices (created_by);

create table public.invoice_drafts (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  recurring_id bigint not null references public.recurring_invoices (id) on delete restrict,
  order_id bigint not null references public.orders (id) on delete restrict,
  issue_date date not null,
  due_date date not null,
  note text,
  lines jsonb not null,
  status text not null default 'draft' check (status in ('draft', 'issued', 'dismissed')),
  invoice_id bigint references public.invoices (id) on delete set null,
  decided_by bigint references public.sales (id) on delete set null,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  constraint invoice_drafts_once unique (recurring_id, issue_date)
);
create index invoice_drafts_org_idx on public.invoice_drafts (organisation_id, status, issue_date);
create index invoice_drafts_order_idx on public.invoice_drafts (order_id);
create index invoice_drafts_invoice_idx on public.invoice_drafts (invoice_id);
create index invoice_drafts_decided_by_idx on public.invoice_drafts (decided_by);

create or replace function private.recurring_invoices_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
begin
  if tg_op = 'INSERT' then
    new.organisation_id := private.current_organisation();
    new.created_by := private.staff_id();
    if new.organisation_id is null or not private.is_admin() then
      raise exception 'Only an administrator can repeat an invoice.' using errcode = '42501';
    end if;
    if not exists (
      select 1 from public.invoices i
       where i.id = new.source_invoice_id and i.organisation_id = new.organisation_id and i.kind = 'invoice'
    ) then
      raise exception 'Only an invoice of your own business can be repeated.' using errcode = '42501';
    end if;
    select i.order_id into new.order_id from public.invoices i where i.id = new.source_invoice_id;
    -- The lines are copied from the invoice by the database, never taken from the sender.
    select jsonb_agg(jsonb_build_object(
             'description', l.description, 'quantity', l.quantity,
             'unit_amount_pence', l.unit_amount_pence, 'vat_code', l.vat_code) order by l.position)
      into new.lines
      from public.invoice_lines l where l.invoice_id = new.source_invoice_id;
    new.anchor_day := extract(day from new.next_date)::int;
    new.last_generated_on := null;
    if new.next_date < current_date then
      raise exception 'The first date must be today or later.';
    end if;
    if new.end_date is not null and new.end_date < new.next_date then
      raise exception 'The end date is before the first date.';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.created_by := old.created_by;
    new.source_invoice_id := old.source_invoice_id;
    new.order_id := old.order_id;
    new.frequency := old.frequency;
    new.anchor_day := old.anchor_day;
    new.lines := old.lines;
    new.updated_at := now();
  end if;
  return new;
end;
$$;
revoke execute on function private.recurring_invoices_before_write() from public, anon, authenticated;

create trigger "10_recurring_invoices_before_write" before insert or update on public.recurring_invoices
  for each row execute function private.recurring_invoices_before_write();
create trigger "90_recurring_invoices_audit" after insert or update or delete on public.recurring_invoices
  for each row execute function private.audit_row();
create trigger "90_invoice_drafts_audit" after insert or update or delete on public.invoice_drafts
  for each row execute function private.audit_row();

alter table public.recurring_invoices enable row level security;
alter table public.invoice_drafts enable row level security;

create policy "administrators read repeating invoices" on public.recurring_invoices for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators add repeating invoices" on public.recurring_invoices for insert to authenticated
  with check (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "administrators change repeating invoices" on public.recurring_invoices for update to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()))
  with check (organisation_id = (select private.current_organisation()));
create policy "administrators read invoice drafts" on public.invoice_drafts for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));

grant select on public.recurring_invoices, public.invoice_drafts to authenticated;
grant insert (source_invoice_id, frequency, next_date, end_date, due_days, note)
  on public.recurring_invoices to authenticated;
