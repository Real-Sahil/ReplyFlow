grant all on public.recurring_invoices, public.invoice_drafts to service_role;

-- Adds a draft for each occurrence due up to p_horizon, for one business or (null) for all of them.
create or replace function private.generate_invoice_drafts(p_org bigint, p_horizon date)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.recurring_invoices;
  v_made int := 0;
  v_next date;
  v_rows int;
begin
  for r in
    select * from public.recurring_invoices
     where active and next_date <= p_horizon and (p_org is null or organisation_id = p_org)
     order by organisation_id, id
     for update skip locked
  loop
    while r.next_date <= p_horizon and (r.end_date is null or r.next_date <= r.end_date) loop
      insert into public.invoice_drafts (organisation_id, recurring_id, order_id, issue_date, due_date, note, lines)
      values (r.organisation_id, r.id, r.order_id, r.next_date, r.next_date + r.due_days, r.note, r.lines)
      on conflict (recurring_id, issue_date) do nothing;
      get diagnostics v_rows = row_count;
      v_made := v_made + v_rows;
      r.last_generated_on := r.next_date;
      r.next_date := private.next_occurrence(r.next_date, r.frequency, r.anchor_day);
    end loop;
    update public.recurring_invoices
       set next_date = r.next_date, last_generated_on = r.last_generated_on
     where id = r.id;
  end loop;
  return v_made;
end;
$$;
revoke execute on function private.generate_invoice_drafts(bigint, date) from public, anon, authenticated;
grant execute on function private.generate_invoice_drafts(bigint, date) to service_role;

create or replace function public.generate_my_invoice_drafts()
returns int
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do this.' using errcode = '42501';
  end if;
  return private.generate_invoice_drafts(private.current_organisation(), current_date + 7);
end;
$$;
revoke execute on function public.generate_my_invoice_drafts() from public, anon;
grant execute on function public.generate_my_invoice_drafts() to authenticated;

-- Confirm a draft: it is issued as a real invoice by issue_invoice(), with the lines and date given (or the
-- draft's own). If issuing fails (for example the books are locked for that date) nothing changes.
create or replace function public.confirm_invoice_draft(
  p_id bigint,
  p_lines jsonb default null,
  p_issue_date date default null,
  p_due_date date default null
) returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  d public.invoice_drafts;
  v_invoice bigint;
  v_issue date;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can confirm an invoice.' using errcode = '42501';
  end if;
  select * into d from public.invoice_drafts
   where id = p_id and organisation_id = private.current_organisation() for update;
  if not found then
    raise exception 'Draft not found.';
  end if;
  if d.status <> 'draft' then
    raise exception 'That draft has already been dealt with.';
  end if;
  v_issue := coalesce(p_issue_date, d.issue_date);
  v_invoice := public.issue_invoice(
    d.order_id, 'invoice', null, coalesce(p_lines, d.lines), v_issue,
    coalesce(p_due_date, case when p_issue_date is null then d.due_date else v_issue + (d.due_date - d.issue_date) end),
    d.note);
  update public.invoice_drafts
     set status = 'issued', invoice_id = v_invoice, decided_by = private.staff_id(), decided_at = now()
   where id = d.id;
  return v_invoice;
end;
$$;

create or replace function public.dismiss_invoice_draft(p_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do this.' using errcode = '42501';
  end if;
  update public.invoice_drafts
     set status = 'dismissed', decided_by = private.staff_id(), decided_at = now()
   where id = p_id and organisation_id = private.current_organisation() and status = 'draft';
  if not found then
    raise exception 'Draft not found, or already dealt with.';
  end if;
end;
$$;

revoke execute on function public.confirm_invoice_draft(bigint, jsonb, date, date) from public, anon;
revoke execute on function public.dismiss_invoice_draft(bigint) from public, anon;
grant execute on function public.confirm_invoice_draft(bigint, jsonb, date, date) to authenticated;
grant execute on function public.dismiss_invoice_draft(bigint) to authenticated;

