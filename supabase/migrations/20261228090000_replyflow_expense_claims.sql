-- Staff expense claims.
--
-- CLAIMANT. A sign-in, created by an administrator and handed over in person (no email is sent), that
-- can do one thing: submit its own expense claims and see their status. Like the accountant, it is kept
-- apart by private.staff_role() answering NULL for it, so every existing "any signed-in staff" rule
-- (customers, messages, orders, money, ...) refuses it without being touched. Its few permissions are
-- added back below, for its own claims and its own receipt photos only.
--
-- CLAIM. pending -> approved or rejected -> paid. Nothing reaches the money book until an administrator
-- pays the claim back; paying writes one money-out entry with the receipt attached. Claims are never
-- deleted: a wrong one is rejected with a reason.

alter table public.sales drop constraint if exists sales_role_check;
alter table public.sales
  add constraint sales_role_check check (role in ('admin', 'agent', 'viewer', 'accountant', 'claimant'));

create or replace function private.staff_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case when s.role in ('accountant', 'claimant') then null else s.role end
  from public.sales s
  where s.user_id = (select auth.uid()) and not s.disabled
  limit 1
$$;

create or replace function private.is_claimant()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.sales s
    where s.user_id = (select auth.uid()) and not s.disabled and s.role = 'claimant'
  )
$$;
revoke execute on function private.is_claimant() from public, anon;
grant execute on function private.is_claimant() to authenticated, service_role;

create policy "claimant reads own row" on public.sales
  for select to authenticated
  using (user_id = (select auth.uid()) and (select private.is_claimant()));

create table public.expense_claims (
  id bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id),
  claimant_id bigint not null references public.sales (id),
  claim_date date not null,
  amount_pence bigint not null check (amount_pence > 0 and amount_pence <= 500000),
  category text not null references public.money_categories (code),
  description text not null check (char_length(trim(description)) > 0 and char_length(description) <= 300),
  receipt_path text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'paid')),
  decided_by bigint references public.sales (id) on delete set null,
  decided_at timestamptz,
  decision_note text,
  paid_at date,
  paid_entry_id bigint references public.money_entries (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index expense_claims_org_status_idx on public.expense_claims (organisation_id, status);
create index expense_claims_claimant_idx on public.expense_claims (claimant_id, created_at desc);
create index expense_claims_decided_by_idx on public.expense_claims (decided_by);
create index expense_claims_paid_entry_idx on public.expense_claims (paid_entry_id);
create index expense_claims_category_idx on public.expense_claims (category);

-- The business, the claimant and the status are set by the database, never by the sender.
create or replace function private.expense_claims_before_write() returns trigger
  language plpgsql security definer
  set search_path = ''
  as $$
declare
  v_staff bigint;
begin
  if tg_op = 'INSERT' then
    v_staff := private.staff_id();
    if v_staff is null or not private.is_claimant() then
      raise exception 'Only an expenses sign-in can submit a claim.' using errcode = '42501';
    end if;
    new.organisation_id := private.current_organisation();
    new.claimant_id := v_staff;
    new.status := 'pending';
    new.decided_by := null;
    new.decided_at := null;
    new.decision_note := null;
    new.paid_at := null;
    new.paid_entry_id := null;
    if new.claim_date > current_date + 1 or new.claim_date < current_date - 366 then
      raise exception 'The date of the spend must be within the last year and not in the future.';
    end if;
    if not exists (
      select 1 from public.money_categories c
      where c.code = new.category and c.direction = 'out' and not c.admin_only
        and c.code in ('stock', 'travel_out', 'office_out', 'equipment_out', 'software_out',
                       'advertising_out', 'delivery_out', 'packaging_out', 'production',
                       'professional_out', 'other_out')
    ) then
      raise exception 'That category cannot be claimed.';
    end if;
    -- A receipt photo must be in this person's own folder.
    if new.receipt_path is not null and new.receipt_path not like
       new.organisation_id::text || '/claims/' || v_staff::text || '/%' then
      raise exception 'The receipt must be one you uploaded.' using errcode = '42501';
    end if;
    -- A limit that stops a slip or a runaway script, not a control on honest use.
    if (select count(*) from public.expense_claims e
        where e.claimant_id = v_staff and e.created_at > now() - interval '24 hours') >= 20 then
      raise exception 'That is a lot of claims for one day. Please try again tomorrow.';
    end if;
  else
    new.organisation_id := old.organisation_id;
    new.claimant_id := old.claimant_id;
    new.updated_at := now();
  end if;
  return new;
end;
$$;
revoke execute on function private.expense_claims_before_write() from public, anon, authenticated;

create trigger "10_expense_claims_before_write" before insert or update on public.expense_claims
  for each row execute function private.expense_claims_before_write();
create trigger "90_expense_claims_audit" after insert or update or delete on public.expense_claims
  for each row execute function private.audit_row();

alter table public.expense_claims enable row level security;

create policy "claimant reads own claims" on public.expense_claims for select to authenticated
  using (claimant_id = (select private.staff_id()) and (select private.is_claimant()));
create policy "claimant submits claims" on public.expense_claims for insert to authenticated
  with check (claimant_id = (select private.staff_id()) and (select private.is_claimant()));
create policy "administrators read claims" on public.expense_claims for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_admin()));
create policy "accountant reads claims" on public.expense_claims for select to authenticated
  using (organisation_id = (select private.current_organisation()) and (select private.is_accountant()));

-- Direct writes are only the claimant's insert. Approving, rejecting and paying go through the
-- functions below, so an administrator cannot change an amount or a claimant by hand.
grant select on public.expense_claims to authenticated;
grant insert (claim_date, amount_pence, category, description, receipt_path)
  on public.expense_claims to authenticated;
grant all on public.expense_claims to service_role;

-- Receipt photos: a claimant can add and open files in its own folder, <business>/claims/<its id>/.
create policy "claimant uploads own receipts" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'attachments'
    and (select private.is_claimant())
    and (storage.foldername(name))[1] = (select private.current_organisation())::text
    and (storage.foldername(name))[2] = 'claims'
    and (storage.foldername(name))[3] = (select private.staff_id())::text
  );
create policy "claimant reads own receipts" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'attachments'
    and (select private.is_claimant())
    and (storage.foldername(name))[1] = (select private.current_organisation())::text
    and (storage.foldername(name))[2] = 'claims'
    and (storage.foldername(name))[3] = (select private.staff_id())::text
  );

-- Approve or reject. A rejection needs a reason the person can read.
create or replace function public.decide_expense_claim(p_id bigint, p_approve boolean, p_note text default null)
returns public.expense_claims
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_claim public.expense_claims;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can decide a claim.' using errcode = '42501';
  end if;
  select * into v_claim from public.expense_claims
   where id = p_id and organisation_id = private.current_organisation() for update;
  if not found then
    raise exception 'Claim not found.';
  end if;
  if p_approve and v_claim.status <> 'pending' then
    raise exception 'Only a waiting claim can be approved.';
  end if;
  if not p_approve and v_claim.status not in ('pending', 'approved') then
    raise exception 'A paid or rejected claim cannot be rejected.';
  end if;
  if not p_approve and char_length(trim(coalesce(p_note, ''))) = 0 then
    raise exception 'Please give a reason, so the person knows why.';
  end if;
  update public.expense_claims
     set status = case when p_approve then 'approved' else 'rejected' end,
         decided_by = private.staff_id(),
         decided_at = now(),
         decision_note = nullif(trim(coalesce(p_note, '')), '')
   where id = p_id
   returning * into v_claim;
  return v_claim;
end;
$$;

-- Pay an approved claim back: one money-out entry, with the receipt, and the claim marked paid.
create or replace function public.pay_expense_claim(p_id bigint, p_date date default current_date, p_method text default 'bank_transfer')
returns public.expense_claims
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_claim public.expense_claims;
  v_name text;
  v_entry bigint;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can pay a claim.' using errcode = '42501';
  end if;
  select * into v_claim from public.expense_claims
   where id = p_id and organisation_id = private.current_organisation() for update;
  if not found then
    raise exception 'Claim not found.';
  end if;
  if v_claim.status <> 'approved' then
    raise exception 'Only an approved claim can be paid.';
  end if;
  if coalesce(p_method, 'bank_transfer') not in ('cash', 'card', 'bank_transfer', 'other') then
    raise exception 'Choose cash, card, bank transfer or other.';
  end if;
  select trim(s.first_name || ' ' || s.last_name) into v_name from public.sales s where s.id = v_claim.claimant_id;

  insert into public.money_entries
    (direction, category, status, entry_date, amount_pence, counterparty, payment_method, reference, receipt_path, note)
  values
    ('out', v_claim.category, 'done', coalesce(p_date, current_date), v_claim.amount_pence, v_name,
     coalesce(p_method, 'bank_transfer'), 'Claim #' || v_claim.id, v_claim.receipt_path,
     'Expense claim: ' || v_claim.description)
  returning id into v_entry;

  update public.expense_claims
     set status = 'paid', paid_at = coalesce(p_date, current_date), paid_entry_id = v_entry
   where id = p_id
   returning * into v_claim;
  return v_claim;
end;
$$;

revoke execute on function public.decide_expense_claim(bigint, boolean, text) from public, anon;
revoke execute on function public.pay_expense_claim(bigint, date, text) from public, anon;
grant execute on function public.decide_expense_claim(bigint, boolean, text) to authenticated, service_role;
grant execute on function public.pay_expense_claim(bigint, date, text) to authenticated, service_role;
