#!/usr/bin/env bash
# Prints the SQL that builds the upstream Atomic CRM baseline on an EMPTY hosted
# Supabase database, from the declarative files in supabase/schemas. Apply it
# first, then supabase/migrations/20261022130000_replyflow_security_baseline.sql.
#
# Why this exists: the upstream migration history has been rewritten many times
# (renames, dropped and re-added functions). The schema files are its current
# end state, so applying them once is simpler and safer than replaying history.
# Later upstream migrations (newer than 20261010054346) still apply normally.
#
# Usage: scripts/hosted-baseline.sh [--no-pg-net] > baseline.sql
#   --no-pg-net   skip "create extension pg_net" (for a local test database)

set -euo pipefail
cd "$(dirname "$0")/.."

with_pg_net=1
[ "${1:-}" = "--no-pg-net" ] && with_pg_net=0

echo "-- Generated by scripts/hosted-baseline.sh. Do not edit."
echo 'create extension if not exists "citext" with schema "extensions";'
echo 'create extension if not exists "unaccent" with schema "extensions";'
if [ "$with_pg_net" = 1 ]; then
  echo 'create extension if not exists "pg_net" with schema "extensions";'
fi

for f in supabase/schemas/0[1-8]*.sql; do
  echo "-- $f"
  # The http extension only served the Gravatar lookup that ReplyFlow removes.
  grep -v 'create extension if not exists "http"' "$f"
done

cat <<'SQL'
-- Seed data that upstream creates in migrations rather than in the schema files.
insert into storage.buckets (id, name, public)
values ('attachments', 'attachments', true)
on conflict (id) do nothing;
insert into public.configuration (id, config)
values (1, '{}'::jsonb)
on conflict (id) do nothing;
SQL
